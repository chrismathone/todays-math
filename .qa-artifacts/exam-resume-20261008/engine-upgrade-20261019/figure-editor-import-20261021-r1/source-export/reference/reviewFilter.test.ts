// math-figure-editor → todays-math: 대조 지적 거르기 시험(문장은 실제 대조 응답 그대로). 위치 제안: src/__tests__/unit/reviewFilter.test.ts
// reviewFilter.ts 를 둔 자리에 맞게 import 경로를 고친다. parseReview 판정 시험은 이 앱 server/ai.ts 전용이라 뺐다.
import { describe, expect, it } from "vitest";
import { filterReviewIssues, isReviewNoise } from "@/lib/dev-ai/reviewFilter";

describe("다시 그릴 이유가 아닌 지적은 거른다", () => {
  it.each([
    "벡터 d 끝점: 원본 (14,6), 재작도 (14,6)이며 일치하므로 수정 불필요",
    "벡터 e 시작점: 원본 (12,1), 재작도 (12,1)로 같으나 원본 화살촉이 더 굵으므로 수정 불필요",
    "벡터 c 시작점: 원본 (11,6), 재작도는 (11,6)으로 같으나 원본이 y=6 선 위에 있고 재작도는 y=6에서 멈춤 – 확인 필요",
    "벡터 a: 원본은 (1,2)→(5,8), 재작도의 선은 같은 격자 좌표로 맞으나 화살촉이 시작점 쪽에도 있는지 확인이 불가하다.",
    "벡터 c 시작점: 원본은 (11,6)인데 재작도 격자에서는 (11,6)이 맞지만 위쪽 눈금이 어긋나 검증이 불확실하다.",
    "벡터 a·c 등 화살표: 원본은 굵고 뚜렷한 화살촉인데 재작도는 화살촉이 너무 작아 거의 보이지 않으므로 키울 것",
    "선분 AB 의 선 굵기가 원본보다 가늘다",
    "모눈 선 색이 원본보다 진하다",
  ])("%s", (issue) => {
    expect(isReviewNoise(issue)).toBe(true);
  });
});

describe("명세로 고칠 수 있는 지적은 남긴다", () => {
  it.each([
    "벡터 b: 원본은 (6,5)→(4,0) 화살표이고 재작도도 같으나, 시작점 쪽에 불필요한 화살촉이 보이므로 시작점 화살촉 제거",
    "벡터 c: 원본은 (11,6)→(7,0)인데 재작도 시작점이 (11,6) 부근에서 정확하지 않아 (11,6)에 맞출 것",
    "벡터 f 끝점: 원본 (15,3)이고 재작도 끝점은 (15,3)이지만 라벨 f가 선에 가깝게 겹쳐 있어 왼쪽으로 옮겨야",
    "끝점은 일치함. 라벨 f 를 왼쪽으로 옮길 것",
    "화살촉 방향이 반대다. 재작도에서 끝점 쪽으로 바꿀 것",
    "선분 CD 가 빠졌다 — 추가할 것",
    "점 H 가 원본보다 한 칸 왼쪽이다, 확인 필요하나 (4,2)로 옮길 것",
  ])("%s", (issue) => {
    expect(isReviewNoise(issue)).toBe(false);
  });
});

describe("모아 거르기", () => {
  it("남은 것과 거른 것을 나눈다", () => {
    expect(filterReviewIssues(["수정 불필요", "선분 CD 추가할 것"])).toEqual({
      kept: ["선분 CD 추가할 것"],
      dropped: ["수정 불필요"],
    });
  });
});
