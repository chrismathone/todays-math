-- 심화를 셋으로 쪼개기 **둘째 걸음** — 갈래를 더한다 (D-113, 원장님 확정 2026-08-30).
--
--   연산 < 기본 < 응용 < 심화하 < 심화중 < 심화상
--
-- ## 왜 이 축인가 — 재서 나온 값이다
--
-- 2026-08-30 벤치마킹: 매쓰홀릭(단원별 문제은행)은 난이도를 **6단**으로 연다 —
-- `개념 · 기본 · 실력(하) · 실력(중) · 심화(하) · 심화(중)`. 우리 4단을 그 눈금에
-- 대니 **우리 사다리의 꼭대기가 저쪽 6단 중 4번째(실력(중))에 닿았다.**
-- 근거는 표본 비교가 아니라 **같은 문형의 직접 대응**이다 — 저쪽이 실력(중)에 두는
-- 「어떤 수에 60을 곱해야 할 것을 잘못하여 더했더니 528」이 우리에게는 초4 **심화**
-- 다(초4·초5 두 학년에서 따로 확인).
--
-- 초3~초6 **230소단원 · 11,040문항 전량**에서 저쪽 「심화(중)」에 앉을 만한 것은
-- **0건**이었다(학년마다 다른 세션이 따로 재서 넷이 같은 답을 냈다).
-- 그래서 이번 확대는 「있는 것을 다시 나누는」 일이 아니라 **없던 층을 만드는** 일이다.
--
-- ## 왜 괄호가 아니라 `심화중`·`심화상` 인가
--
-- Prisma 가 enum 값에 괄호를 못 받는다(직접 돌려 확인). `@map` 으로 우회하면 DB
-- 라벨과 코드 값이 갈려 **어휘가 두 벌**이 된다 — 앞 회차(20260830120000) 머리말에
-- 적은 그대로다.
--
-- ## 값의 «자리»가 곧 사다리다
--
-- `ADD VALUE … AFTER` 로 순서를 못 박는다. `ORDER BY difficulty` 가 사다리 순서로
-- 나와야 하고, `shiftDifficulty`(한 단계 올리기/내리기)와 `balanceDifficulty` 의
-- 인접 대체가 그 순서를 뜻으로 쓴다.
--
-- ⚠️ **행은 한 줄도 안 옮긴다.** 지금 `심화하` 인 3,270건을 「사실은 중이 아닐까」로
--    다시 앉히지 않는다 — 위 조사가 「심화(중)에 앉을 것은 0건」이라고 했으므로
--    옮길 근거가 없다. 새 두 갈래는 **앞으로 만들 문항**의 자리다.

ALTER TYPE "difficulty" ADD VALUE '심화중' AFTER '심화하';
ALTER TYPE "difficulty" ADD VALUE '심화상' AFTER '심화중';

-- ── 반의 난이도 배분(jsonb) ─────────────────────────────────────────────
--
-- 🔴 **새 갈래는 0 으로 넣는다.** 콘텐츠가 아직 없는데 비율을 주면 출제가 그 자리를
--    못 채우고 **시험지가 조용히 얇아진다** — 부족이 에러로 안 나므로 아무도 모른다.
--    원장님이 프리셋을 정하시면 그때 옮긴다(D-71: 숫자는 원장님이 언제든 조정).
--
-- ⚠️ 키가 **이미 있으면 덮지 않는다** — 원장님이 손댄 반의 값을 지어내지 않는다.
UPDATE "class"
   SET "difficulty_ratio" =
         "difficulty_ratio"
         || jsonb_build_object(
              '심화중', COALESCE(("difficulty_ratio"->>'심화중')::int, 0),
              '심화상', COALESCE(("difficulty_ratio"->>'심화상')::int, 0));

-- 분석 보고서의 난이도 분포도 여섯 칸이 **전부** 있어야 한다 — 계약이 그렇게 요구한다
-- (`z.record(difficultySchema, …)`). D-106 때 한 칸이 비어 상세 조회가 500 을 냈다.
UPDATE "analysis_report"
   SET "difficulty_distribution" =
         "difficulty_distribution"
         || jsonb_build_object(
              '심화중', COALESCE("difficulty_distribution"->'심화중',
                                 jsonb_build_object('correct', 0, 'total', 0)),
              '심화상', COALESCE("difficulty_distribution"->'심화상',
                                 jsonb_build_object('correct', 0, 'total', 0)));
