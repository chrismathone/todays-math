-- 심화를 셋으로 쪼개기 **첫 걸음** — 이름만 바꾼다 (D-113, 원장님 확정 2026-08-30).
--
--   연산 < 기본 < 응용 < 심화하        ← 이번 회차
--   연산 < 기본 < 응용 < 심화하 < 심화중 < 심화상   ← 다음 회차(20260830130000)
--
-- ## 왜 두 걸음인가
--
-- 한 번에 「이름 바꾸고 둘 더하기」를 하면, 관문이 빨개졌을 때 **이름 탓인지 새 갈래
-- 탓인지 못 가른다.** 이름 바꾸기만 해도 코드 109개 파일 884줄이 움직인다.
-- 그래서 이 회차는 **4단을 그대로 둔 채 이름만** 바꾸고 관문을 초록으로 만든다.
--
-- ## 왜 괄호가 아니라 `심화하` 인가
--
-- 원장님이 고르신 표기는 `심화(하)` 였다. 그런데 **Prisma 는 enum 값에 괄호를 못
-- 받는다** — 직접 돌려서 확인했다(`This line is not an enum value definition`).
-- `@map("심화(하)")` 로 우회하면 DB 라벨은 `심화(하)`, 코드 값은 `심화하` 가 되어
-- **어휘가 두 벌**이 된다. 이 저장소가 반복해서 데인 자리다(D-106 이 축이 둘이라
-- 겪은 것과 같은 성질). 그래서 값은 하나로 `심화하` 로 두고, 화면에 괄호를 붙일지는
-- **지면에 그리는 순간 한 곳에서** 정한다(D-108 이 상자 라벨에 쓴 방식).
--
-- ## 왜 «더하기»가 아니라 **이름 바꾸기**인가
--
-- `ALTER TYPE … RENAME VALUE` 는 **라벨만** 바꾼다 — 행을 한 줄도 UPDATE 하지 않는다.
-- 그래서 바깥벽 트리거(`enforce_registered_problem_outer_wall`, BEFORE UPDATE)가
-- **발동조차 안 한다.** `심화` 를 단 행을 UPDATE 로 옮기려 했으면 벽을 내려야 했고,
-- 그 벽은 원장님이 세우라고 하신 것이다. D-106 이 `easy→기본` 에 쓴 그 방법이다.
--
-- 그리고 뜻이 안 변한다 — 지금 `심화` 인 문항은 벤치마킹 실측에서 **대부분 저쪽
-- 「심화(하)」 언저리**였다(초3~초6 230소단원 11,040문항, 2026-08-30). 옮겨 앉히는
-- 것이 아니라 **원래 자리에 이름을 붙이는** 일이다. 「심화(중)에 앉을 만한 것」은
-- 그 조사에서 **0건**이었으므로 이 rename 이 누구를 잘못 내리지 않는다.

ALTER TYPE "difficulty" RENAME VALUE '심화' TO '심화하';

-- ── 반의 난이도 배분(jsonb) ─────────────────────────────────────────────
--
-- enum 라벨은 바뀌어도 jsonb 의 **문자열 키는 안 바뀐다.** 여기를 같이 안 고치면
-- 화면이 `심화하` 를 찾는데 값에는 `심화` 가 있어 **조용히 0으로 읽힌다** — 에러가
-- 안 난다. D-106 이 같은 자리에서 세 테이블을 같이 고쳤다.
--
-- ⚠️ `- '심화'` 로 옛 키를 **반드시 지운다.** 안 지우면 두 키가 같이 남아
--    「합이 문항 수와 안 맞는다」가 조용히 생긴다.
UPDATE "class"
   SET "difficulty_ratio" =
         ("difficulty_ratio" - '심화')
         || jsonb_build_object('심화하', COALESCE(("difficulty_ratio"->>'심화')::int, 0))
 WHERE "difficulty_ratio" ? '심화';

-- 분석 보고서의 난이도 분포도 같은 열쇠를 쓴다.
UPDATE "analysis_report"
   SET "difficulty_distribution" =
         ("difficulty_distribution" - '심화')
         || jsonb_build_object('심화하',
              COALESCE("difficulty_distribution"->'심화',
                       jsonb_build_object('correct', 0, 'total', 0)))
 WHERE "difficulty_distribution" ? '심화';
