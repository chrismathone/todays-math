-- 값 이름이 `textbook` 이 아닌 까닭: 이 저장소에서 그 낱말은 이미 «교재»를 가리킨다
-- (자체 교재 제작의 `textbook_*` 표들 · RPM 문제집 스크립트). 교과서는 `school_textbook` 이다.
