-- 🔴 **enum 값은 한번 넣으면 못 뺀다**(PostgreSQL 에 DROP VALUE 가 없다). 되돌리기는 «이 값을 쓰는 행이
--    0 인 채로 둔다»뿐이다 — 값이 남아 있어도 아무도 안 쓰면 해가 없다.
-- 🔴 **이 값을 모르는 옛 Prisma 클라이언트는 이 값을 가진 행을 읽다 죽는다.** 그래서 순서가 있다:
--    ① 이 파일(DB) → ② 이 값을 아는 코드를 main 에 올려 배포 → ③ 그 뒤에야 교과서 문항을 넣는다.
--    ①만으로는 아무 행도 바뀌지 않으므로 옛 코드는 그대로 돈다.
-- 🔴 `prisma migrate dev` · `migrate deploy` · `db push` 로 적용하지 않는다 — 다른 트랙의 미적용 초안까지 같이 나간다.
--    적용은 scripts/qa/apply-source-material-migration.ts 로, 드라이런 먼저.
--
-- 값을 더하는 문장은 그 값을 **쓰는** 문장과 한 트랜잭션에 둘 수 없다 — 그래서 이 파일은 이 한 문장뿐이다.
-- `IF NOT EXISTS` 인 까닭: 뒤의 둘(표 · 칸)을 되돌린 뒤에도 이 값은 남는다 — 그 DB 에 다시 적용할 수 있어야 한다.

-- AlterEnum
ALTER TYPE "problem_source" ADD VALUE IF NOT EXISTS 'school_textbook';
