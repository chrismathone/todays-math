/** Offline-only: tsx scripts/qa/arithmetic-typography-build.ts [--census]
 * Uses the actual editor engine. Does not regenerate or modify published SVGs.
 */
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { deflateSync } from "node:zlib";
import { format } from "prettier";
import angleAssets from "../../src/lib/arithmetic-v2/families/geometry-angle-assets-v1.json";
import { EXTRA_GEOMETRY_FIGURE_MAPS } from "../../src/lib/arithmetic-v2/extraGeometry";
import {
  placeLabel,
  typesetLabel,
} from "../../src/components/unified/figure-editor/mathjaxLabel";
import {
  arithmeticLabelParts,
  unescapeTypographyXml,
} from "../../src/lib/arithmetic-v2/presentation/typographyLabel";

async function main() {
  const out = path.resolve("tmp/arithmetic-typography");
  await mkdir(out, { recursive: true });
  const labels = new Map<string, { count: number; exampleId: string }>();
  const math = new Set<string>();
  const sourceHash = createHash("sha256");
  let figures = 0,
    placements = 0;
  for (const map of EXTRA_GEOMETRY_FIGURE_MAPS) {
    for (const [id, svg] of Object.entries(map)) {
      figures++;
      sourceHash.update(id).update("\0").update(svg).update("\0");
      for (const match of svg.matchAll(/<text\b[^>]*>([\s\S]*?)<\/text>/g)) {
        const text = unescapeTypographyXml(match[1]);
        const record = labels.get(text) ?? { count: 0, exampleId: id };
        record.count++;
        placements++;
        labels.set(text, record);
        for (const part of arithmeticLabelParts(text))
          if (part.tex) math.add(part.tex);
      }
    }
  }
  // Small documented compatibility vocabulary. No unbounded numeric range.
  for (const text of ["0", "2m", "ABC", "r", "x", "1/2", "cm²", "cm³"])
    for (const part of arithmeticLabelParts(text))
      if (part.tex) math.add(part.tex);
  const census = {
    figures,
    placements,
    uniqueLabels: labels.size,
    uniqueMath: math.size,
    alreadyTypedAngleFigures: angleAssets.entries.length,
    sourceSha256: sourceHash.digest("hex"),
    labels: [...labels].map(([text, record]) => ({
      text,
      ...record,
      parts: arithmeticLabelParts(text),
    })),
  };
  await writeFile(
    path.join(out, "census.json"),
    JSON.stringify(census, null, 2),
  );
  console.log(JSON.stringify({ ...census, labels: undefined }));
  if (process.argv.includes("--census")) return;

  const glyphs: string[] = [];
  const glyphIds = new Map<string, number>();
  const entries: Record<string, [number, number, number, string]> = {};
  for (const tex of [...math].sort()) {
    const laid = typesetLabel(tex);
    assert.ok(laid, `Editor cannot typeset ${tex}`);
    assert.ok(!/<(?:text|merror)\b|data-mjx-error/.test(laid.inner), tex);
    const placed = placeLabel(laid, "", 0, 0, 1000, "currentColor", undefined, {
      anchor: "start",
    });
    assert.ok(placed, tex);
    const body = placed.slice(placed.indexOf(">") + 1, -4);
    const template = body.replace(/<path\b[^>]*><\/path>/g, (glyph) => {
      let index = glyphIds.get(glyph);
      if (index === undefined) {
        index = glyphs.length;
        glyphs.push(glyph);
        glyphIds.set(glyph, index);
      }
      return `~${index}~`;
    });
    entries[tex] = [laid.widthEm, laid.ascentEm, laid.descentEm, template];
  }
  const data = JSON.stringify({
    centerShiftEm: typesetLabel("0")!.ascentEm / 2,
    glyphs,
    entries,
  });
  const compressed = deflateSync(Buffer.from(data), { level: 9 });
  const packed = compressed.toString("base64");
  assert.ok(
    packed.length <= 150_000,
    `Dictionary budget exceeded: ${packed.length}`,
  );
  const engineFiles = ["mathjaxLabel.ts", "mathjaxBrowserVersion.ts"];
  const engineHash = createHash("sha256");
  for (const name of engineFiles)
    engineHash.update(
      await readFile(
        path.resolve("src/components/unified/figure-editor", name),
      ),
    );
  const manifest = {
    figures,
    placements,
    uniqueLabels: labels.size,
    uniqueMath: math.size,
    alreadyTypedAngleFigures: angleAssets.entries.length,
    glyphs: glyphs.length,
    decodedBytes: Buffer.byteLength(data),
    packedBase64Bytes: packed.length,
    compressedBytes: compressed.length,
    sourceSha256: census.sourceSha256,
    editorSha256: engineHash.digest("hex"),
  };
  const target = path.resolve(
    "src/lib/arithmetic-v2/presentation/typographyData.ts",
  );
  await writeFile(
    target,
    await format(
      `// Generated by scripts/qa/arithmetic-typography-build.ts; do not hand edit.\n` +
        `// Exact editor MathJax paths and metrics, with repeated paths interned.\n` +
        `export const arithmeticTypographyManifest = ${JSON.stringify(manifest, null, 2)} as const;\n` +
        `export const arithmeticTypographyPacked =\n  ${JSON.stringify(packed)};\n`,
      { parser: "typescript" },
    ),
  );
  await writeFile(
    path.join(out, "build.json"),
    JSON.stringify(manifest, null, 2),
  );
  console.log(JSON.stringify(manifest, null, 2));
}

main().catch((error: unknown) => {
  console.error(error);
  process.exitCode = 1;
});
