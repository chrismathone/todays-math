import { chromium, expect } from "@playwright/test";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

const output = path.resolve("scratch/math-text-editor-qa");
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1100, height: 1050 } });
const errors = [];
page.on("pageerror", error => errors.push(error.message));
const results = [];
try {
  await page.goto(process.env.EDITOR_FIXTURE_URL ?? "http://127.0.0.1:4319");
  const body = page.getByRole("textbox", { name: "문제 본문", exact: true });
  const value = page.getByTestId("value");
  await expect(body).toBeVisible();
  const initial = await value.textContent();
  await expect(body.locator(".choice")).toHaveCount(5);
  await expect(body.locator(".visual-condition")).toHaveAttribute("data-condition-box", "2");
  await expect(body.locator("table tr")).toHaveCount(2);
  await page.getByRole("button", { name: "원문 코드", exact: true }).click();
  await expect(page.getByRole("textbox", { name: "문제 본문 (Markdown + LaTeX)", exact: true })).toHaveValue(initial);
  await page.getByRole("button", { name: "직접 편집으로" }).click();
  await expect(value).toHaveText(initial);
  results.push("Initial source-mode roundtrip preserves the exact input.");

  await body.locator("p").last().click();
  await page.keyboard.press("End");
  await page.keyboard.insertText(" 직접 수정");
  await expect(value).toContainText("마지막 문장. 직접 수정");
  const edited = await value.textContent();
  expect(edited).toContain(String.raw`$\dfrac{1}{2}$`);
  expect(edited).toContain(String.raw`$\frac{}{2}$`);
  expect(edited).toContain("<보기:cols=2>");
  expect(edited).toContain("⑤ $5$");
  expect(edited).toContain(String.raw`| 분수 | $\frac{3}{4}$ |`);
  expect(edited).toContain("[그림1]");
  await page.getByRole("button", { name: "본문 되돌리기" }).click();
  await expect(value).not.toContainText("직접 수정");
  await page.getByRole("button", { name: "본문 다시 실행" }).click();
  await expect(value).toContainText("직접 수정");
  results.push("Direct typing serializes conditions, choices, table math and figure anchors; undo/redo restore text.");

  await page.getByRole("button", { name: "그림 1 편집" }).click();
  await expect(page.getByTestId("clicked")).toHaveText("0");
  const beforeRedraw = await value.textContent();
  await page.getByRole("button", { name: "그림 새로 그리기" }).click();
  await expect(body.locator(".visual-figure")).toContainText("Redrawn");
  await expect(value).toHaveText(beforeRedraw);
  await page.getByRole("button", { name: "본문 되돌리기" }).click();
  await expect(value).not.toContainText("직접 수정");
  await expect(body.locator(".visual-figure")).toContainText("Redrawn");
  await page.getByRole("button", { name: "본문 다시 실행" }).click();
  results.push("Figure callback, redraw-only prop update and document history remain independent.");

  await body.getByRole("button", { name: "수식 편집", exact: true }).first().click();
  const field = body.locator("math-field");
  await expect(field).toBeVisible();
  await expect(page.getByRole("region", { name: "수식 키보드", exact: true })).toBeVisible();
  await page.keyboard.press("Control+a");
  await page.keyboard.type("7/8");
  await expect.poll(() => field.evaluate(element => element.value)).toContain("7");
  await page.keyboard.press("Escape");
  await expect(field).toHaveCount(0);
  await expect(value).toContainText("7");
  results.push("Click activates a real MathLive field; physical keyboard entry is saved.");

  await body.locator("p").last().click();
  await page.keyboard.press("End");
  await page.getByRole("toolbar", { name: "수식 삽입" }).getByRole("button", { name: "분수", exact: true }).click();
  await expect(field).toBeVisible();
  const keypad = page.getByRole("region", { name: "수식 키보드", exact: true });
  await keypad.getByRole("button", { name: "3", exact: true }).click();
  await page.keyboard.press("Tab");
  await page.keyboard.type("4");
  await expect.poll(() => field.evaluate(element => element.value)).toMatch(/\\frac(?:\{3\}|3)(?:\{4\}|4)/);
  await page.screenshot({ path: path.join(output, "mathlive-fraction.png"), fullPage: true });
  await page.keyboard.press("Escape");
  await expect(value).toContainText(String.raw`\frac{3}{4}`);
  results.push("Fraction template exposes separate numerator/denominator fields; compact keypad and physical keys enter 3/4.");

  await body.locator("table td").first().click();
  await page.keyboard.press("End");
  await page.keyboard.insertText(" 수정");
  await expect(value).toContainText("| 분수 수정 |");
  const beforeSource = await value.textContent();
  await page.getByRole("button", { name: "원문 코드", exact: true }).click();
  const source = page.getByRole("textbox", { name: "문제 본문 (Markdown + LaTeX)", exact: true });
  await expect(source).toHaveValue(beforeSource);
  await source.fill(beforeSource + "\n\n원문에서 추가한 $z^3$.");
  await page.getByRole("button", { name: "직접 편집으로" }).click();
  await expect(body).toContainText("원문에서 추가한");
  await expect(body.locator(".choice")).toHaveCount(5);
  await expect(body.locator("table tr")).toHaveCount(2);
  await expect(body.locator(".visual-condition")).toHaveAttribute("data-condition-box", "2");
  await page.getByRole("button", { name: "저장", exact: true }).click();
  await expect(page.getByTestId("saved")).toHaveText(await value.textContent());
  await page.screenshot({ path: path.join(output, "editor-roundtrip.png"), fullPage: true });
  results.push("Real table-cell edit, optional source edit, visual reload and parent save preserve the document structure.");
  await page.getByRole("button", { name: "외부 값 복원" }).click();
  await expect(value).toHaveText(initial);
  await expect(body).not.toContainText("원문에서 추가한");
  await page.getByRole("button", { name: "두 그림 배치" }).click();
  await page.getByRole("button", { name: "원문 코드", exact: true }).click();
  const rowSource = "두 그림입니다.\n\n[그림2]\n\n[그림1]\n\n> <조건>\n>\n>\n\n끝 문장.";
  await source.fill(rowSource);
  await page.getByRole("button", { name: "직접 편집으로" }).click();
  await expect(body.locator(".figure-row > .visual-figure")).toHaveCount(2);
  expect(await body.locator(".figure-row > .visual-figure").evaluateAll(elements => elements.map(element => element.dataset.figureIndex))).toEqual(["0", "1"]);
  await expect(body.locator(".visual-condition")).toHaveCount(0);
  await page.getByRole("button", { name: "읽기 화면 확인" }).click();
  const read = page.getByTestId("read");
  await expect(read.locator(".figure-row [data-figure-index]")).toHaveCount(2);
  expect(await read.locator(".figure-row [data-figure-index]").evaluateAll(elements => elements.map(element => element.dataset.figureIndex))).toEqual(["0", "1"]);
  await expect(read.locator("[data-condition-box]")).toHaveCount(0);
  await read.getByRole("button", { name: "그림 2 편집", exact: true }).focus();
  await page.keyboard.press("Enter");
  await expect(page.getByTestId("clicked")).toHaveText("1");
  await page.getByRole("button", { name: "읽기 화면 확인" }).click();
  await body.locator("p").last().click();
  await page.keyboard.press("End");
  await page.keyboard.insertText(" [대괄호] *별표* $가격$");
  await page.getByRole("button", { name: "원문 코드", exact: true }).click();
  const literalMarkdown = await source.inputValue();
  expect(literalMarkdown).toContain(String.raw`\[대괄호\] \*별표\* \$가격\$`);
  await page.getByRole("button", { name: "직접 편집으로" }).click();
  await expect(body).toContainText("[대괄호] *별표* $가격$");
  await expect(body.locator(".figure-row > .visual-figure")).toHaveCount(2);
  results.push("Source read/edit share figure-row geometry and keyboard callback; empty condition quotes disappear and literal Markdown punctuation survives.");

  await page.getByRole("button", { name: "원문 코드", exact: true }).click();
  await source.fill("발문이 같은 문단에 있습니다. ① [그림1] ② $2$ ③ $3$ ④ $4$ ⑤ $5$\n\n> <조건>\n> $x < y$\n\n끝.");
  await page.getByRole("button", { name: "직접 편집으로" }).click();
  await expect(body).toContainText("발문이 같은 문단에 있습니다.");
  await expect(body.locator(".choice .visual-figure")).toHaveCount(1);
  await expect(body.locator(".visual-condition .visual-math")).toHaveCount(1);
  await body.locator("p").last().click();
  await page.keyboard.press("End");
  await page.keyboard.insertText(" 수정");
  await expect(value).toContainText("① [그림1]");
  const beforeChoiceRedraw = await value.textContent();
  await page.getByRole("button", { name: "그림 새로 그리기" }).click();
  await expect(body.locator(".choice .visual-figure")).toContainText("Redrawn");
  await expect(value).toHaveText(beforeChoiceRedraw);
  await page.getByRole("button", { name: "본문 되돌리기" }).click();
  await expect(value).not.toContainText("끝. 수정");
  await expect(body.locator(".choice .visual-figure")).toContainText("Redrawn");
  results.push("Choice figures remain inline and indexed, leading question prose is retained, and math-only condition lines are editable.");
  await page.getByRole("button", { name: "원문 코드", exact: true }).click();
  await source.fill("그림 마커가 없는 본문입니다.");
  await page.getByRole("button", { name: "직접 편집으로" }).click();
  await expect(page.locator(".visual-editor [data-editor-standalone-figures] [data-figure-index]")).toHaveCount(1);
  await page.getByRole("button", { name: "그림 1 편집", exact: true }).click();
  await expect(page.getByTestId("clicked")).toHaveText("0");
  await expect(value).toHaveText("그림 마커가 없는 본문입니다.");
  await page.getByRole("button", { name: "읽기 화면 확인" }).click();
  await expect(read.locator("[data-figure-index]")).toHaveCount(1);
  await page.getByRole("button", { name: "그림 편집 잠금" }).click();
  await expect(read.getByRole("button")).toHaveCount(0);
  await expect(page.locator(".visual-editor [data-editor-standalone-figures] [role=button]")).toHaveCount(0);
  await expect(value).toHaveText("그림 마커가 없는 본문입니다.");
  results.push("Marker-free figures appear exactly once in read and edit, retain callback indexes, honor edit locks, and never add stored markers on open.");
  expect(errors).toEqual([]);
  results.push("Controlled value replacement works under React StrictMode with no browser errors.");
  console.log(JSON.stringify({ passed: results.length, results }, null, 2));
  await writeFile(path.join(output, "results.json"), JSON.stringify({ passed: results.length, results, errors }, null, 2));
} catch (error) {
  await page.screenshot({ path: path.join(output, "failure.png"), fullPage: true });
  await writeFile(path.join(output, "failure.json"), JSON.stringify({ results, errors, error: String(error), html: await page.content() }, null, 2));
  throw error;
} finally {
  await browser.close();
}
