def term_keys(grade: str) -> list[tuple[str, T]]:
    """(열쇠, 용어) — 쪽 순서. 같은 쪽에 같은 이름이 두 번이면 `#2`(1-1 p176 원점·좌표)."""
    seen: dict[str, int] = {}
    out = []
    for t in sorted(TERMS[grade], key=lambda x: x.page):
        base = f"{grade}/p{t.page:03d}/{t.term}"
        seen[base] = seen.get(base, 0) + 1
        out.append((base if seen[base] == 1 else f"{base}#{seen[base]}", t))
    return out


