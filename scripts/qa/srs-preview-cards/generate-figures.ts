/** Local-only generation. Uses render_spec.py's existing renderer + sanitizer, never a server/DB. */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { PREVIEW_FIGURE_SPECS } from "../../../src/lib/math-srs/preview/figureSpecs";

export function renderPreviewFigures(): Record<string, string> {
  return Object.fromEntries(
    Object.entries(PREVIEW_FIGURE_SPECS).map(([id, spec]) => {
      const result = JSON.parse(
        execFileSync(
          process.env.PYTHON_BIN ?? "python",
          ["scripts/figure/render_spec.py"],
          {
            input: JSON.stringify(spec),
            encoding: "utf8",
            timeout: 15000,
            env: { ...process.env, PYTHONIOENCODING: "utf-8" },
          },
        ),
      ) as { svg?: string; error?: string };
      if (!result.svg) throw new Error(`${id}: ${result.error}`);
      // Only presentation changes: the existing number line's ink/accent/white.
      // Coordinates, cell membership, transforms and symmetry marks remain engine-owned.
      const svg = result.svg
        .replaceAll("#111111", "#172b4d")
        .replaceAll('fill="#e2b48a"', 'fill="#3159df" fill-opacity="0.22"')
        .replaceAll("#f4efe6", "#ffffff")
        .replaceAll(
          'stroke-width="0.9"',
          'stroke-width="0.9" stroke-opacity="0.3"',
        );
      return [id, svg];
    }),
  );
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  const output = "src/lib/math-srs/preview/generatedFigures.ts";
  const source = `// Generated by scripts/qa/srs-preview-cards/generate-figures.ts — do not edit.\n// prettier-ignore\nexport const PREVIEW_ENGINE_SVGS = ${JSON.stringify(renderPreviewFigures(), null, 2)} as const;\n`;
  if (process.argv.includes("--check")) {
    if (readFileSync(output, "utf8") !== source)
      throw new Error("예습 SVG를 다시 생성해야 합니다.");
  } else writeFileSync(output, source);
}
