/**
 * 초등 원장 키 — `학년|소단원 코드` (예: `"초3|1-2-5"`).
 *
 * ⚠️ **소단원 «이름»을 키로 쓰지 않는다.** 이름은 바뀌고, 바뀌면 그 행이 조용히
 *    아무것도 안 가리키게 되어 그 갈래가 다시 «미검토»로 돌아온다 — 그건 옳지만
 *    **왜 돌아왔는지**가 안 보인다. 코드는 `difficulty.ts` 가 이미 키로 쓰는 값이다.
 *
 * ⚠️ **여기 두는 까닭**: 판정기 파일에 두면 원장을 만드는 쪽이 그 파일을 import 하면서
 *    **전량 쓸기가 통째로 한 번 더 돈다**(실제로 그랬다). 규칙 모듈은 부작용이 없다.
 */
export function elemKey(grade: string, section: string): string {
  return `${grade}|${section.split(" ")[0]}`;
}

/**
 * 판정 하나. **원장을 «있으면 통과»로 쓰지 않는다** — `고칠것` 은 통과가 아니다.
 * 「원장에 적혀 있으니 초록」이면 결함을 적어 두는 것만으로 사라진다.
 */
export type Tier4Judgement =
  | { 판정: "표지있음"; 표지: string[] }
  | { 판정: "검토됨"; 왜: string }
  | { 판정: "고칠것"; 왜: string }
  | { 판정: "미검토" };

export function judgeDeep(
  key: string,
  contents: readonly string[],
  ledger: Record<string, Tier4ReviewRow>,
): Tier4Judgement {
  // ⚠️ **모든 씨앗**이 표지를 가져야 «표지있음»이다. 하나라도 없으면 그 변형은
  //    사람이 봐야 한다 — 실측으로 「12개 중 2개만 표지 0」인 갈래가 27개였고,
  //    그중 진짜 결함이 있었다(초4 1-2-5 는 4/12 만 맨 나눗셈이다).
  const bare = contents.filter((c) => marksOf(c).length === 0);
  if (bare.length === 0)
    return { 판정: "표지있음", 표지: marksOf(contents[0] ?? "") };
  const row = ledger[key];
  if (!row) return { 판정: "미검토" };
  return row.판정 === "4단"
    ? { 판정: "검토됨", 왜: row.왜 }
    : { 판정: "고칠것", 왜: row.왜 };
}

