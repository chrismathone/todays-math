/** 발문이 가진 표지 이름들. 빈 배열이면 «표지 0» — 사람이 볼 몫이다. */
export function marksOf(content: string): string[] {
  return TIER4_MARKS.filter((m) => m.re.test(content)).map((m) => m.name);
}

