/**
 * 식 뒤에 **붙어 쓰는** 조사 · 서술격(이다 활용) — D-164 ⑴(2026-10-21 리드 · Codex 합의)의 «확인한 목록».
 *
 * 한글 맞춤법 41항: 조사는 앞말에 붙여 쓴다. 식(«$x$»)은 체언처럼 읽히므로 «$x$의» · «$25$입니다» 로 붙인다.
 * 붙여 써도 지면이 식과 조사 사이에서 줄을 바꿀 수 있어서(KaTeX 상자는 원자 인라인이다), 렌더러가 그 자리를
 * 잇는다(`rehypeMathNowrap.ts` 의 `joinParticles`).
 *
 * ## 판정은 «낱말 전체»로 — 첫 글자로 가르지 않는다
 *
 * 식 바로 뒤 한글 낱말이 **조사가 겹치는 규칙**(아래 `PARTICLE_WORD`)대로 이어진 조사 · 서술격일 때만 조사다.
 * «$x$에서는»(에서 + 는) · «$3$까지이므로»(까지 + 이므로) · «$x$만을»(만 + 을)은 잇고, 앞 글자가 같아도 낱말이 다르면
 * 잇지 않는다: «$3$가지» · «$2$도막»(의존명사 · 단위) · «$3$이상이다» · «$x$이때»(독립 낱말) · «$3$개»(단위).
 * 겹침 규칙 — 조사는 아무렇게나 겹치지 않는다(2026-10-21 Codex 검토: «$a-b=-1$이를 연립하여» 의 «이를» 이 «이 + 를» 로
 * 통과했다 — 주격 뒤에 목적격은 안 온다):
 *   · 주격 · 목적격 · 관형격(이 가 을 를 의)과 «은 · 는 · 도» 뒤에는 아무것도 안 붙는다
 *   · 부사격 · 접속(에 · 에서 · 로 · 와 …) 뒤에는 «은 · 는 · 도 · 의» · «와 · 과» · «만 · 까지 · 부터 …» 가 붙는다(«에서는» · «로의» · «에서와» · «에만»)
 *   · «만 · 까지 · 부터 · 만큼 · 뿐 · 마다» 뒤에는 격조사 · «은 · 는 · 도» · 부사격 · 서술격이 붙는다(«까지의» · «만으로» · «뿐이다»)
 *   · 서술격은 끝이다 — «인지 · 임» 만 «는 · 를 · 을 …» 가 더 붙는다(«인지는» · «임을»)
 * 단위 · 의존명사 · 독립 낱말은 이번 합의 범위 밖이다(«$3$ 개» · «$3$ 이상» 은 띄어 쓴 채 둔다).
 *
 * ## 근거 — 공유 DB 문항 118,246행(본문 · 정답 · 해설)에서 «식 바로 뒤 한글 낱말»을 센 것 (2026-10-21, 읽기 전용)
 *
 * 붙은 낱말 677,088곳 · 1,298종. 첫 글자만 보면 이었을 것 가운데 낱말 판정이 거른 것은 «가지» · «도막» · «이때» · «과목» ·
 * «만원» 과 띄어쓰기 오타(«이고피타고라스»)였고, 겹침 규칙이 거른 것은 «이를» 과 날 수 «$3$일의 · $3$일이 · $3$일마다 …»
 * (서술격 «일» 은 끝이다)다. 목록에 없는 붙은 낱말은 단위 · 의존명사(개 · 명 · 분 · 원 · 칸 …), 복합 명사(좌표 · 절편 · 축 ·
 * 사분면), 접미사(씩 · 째 · 짜리)다 — 처음 목록에서 빠진 조사는 «뿐»(보조사, 706곳) 하나였고 넣었다.
 *
 * ## ⚠️ 같은 글자가 둘 — 렌더러는 둘 다 잇는다, 생성기는 이것만으로 띄어쓰기를 정하지 않는다
 *
 * «일»은 서술격(«$x=3$일 때»)과 날 수(«$3$일»), «인»은 서술격(«$x$인 경우»)과 사람 수(«$3$인 가족»), «만»은 보조사
 * («$x$만»)와 수(«$3$만»)가 같은 글자다. 붙어 있으면 렌더러는 어느 뜻이든 잇는다 — 글은 한 글자도 안 바뀌고 줄만 안
 * 갈린다. 그러나 이 함수가 «조사다»라고 한 것을 근거로 생성기가 **빈칸을 지우면** 단위 · 수까지 붙는다(합의 범위 밖).
 * 생성기의 붙임은 문장 틀에서 그 자리의 뜻을 보고 정한다(D-164 ⑴ — 전역 정규식 금지).
 */

/** 주격 · 목적격 · 관형격 — 뒤에 다른 조사가 안 붙는다. «$x$가» · «$x$를» · «$x$의». */
const CLOSING_CASE = ["이", "가", "을", "를", "의"] as const;
/** 끝나는 보조사 · 선택. «$x$는» · «$x$도» · «$x$나 $y$». */
const CLOSING_AUX = ["은", "는", "도", "나", "이나"] as const;
/** 부사격 · 접속 — 뒤에 보조사 · 관형격이 붙을 수 있다. «$x$에서는» · «$x$와의» · «$x$로만». */
const ADVERBIAL = [
  "에",
  "에서",
  "에게",
  "에게서",
  "로",
  "으로",
  "로서",
  "으로서",
  "로써",
  "으로써",
  "로부터",
  "으로부터",
  "와",
  "과",
  "보다",
  "처럼",
  "랑",
  "이랑",
] as const;
/** 범위 보조사 — 뒤에 격조사 · 서술격이 더 붙을 수 있다. «$3$까지의» · «$x$만을» · «$5$뿐이다». */
const RANGE_AUX = ["만", "까지", "부터", "만큼", "뿐", "마다"] as const;
/**
 * 서술격 조사 «이다» 의 활용. 식은 받침 유무로 읽히지 않아 «이»가 빠진 꼴(«$x$라고» · «$x$였다»)도 쓰인다.
 * «인지 · 임» 은 뒤에 조사가 더 붙는다(`NOUN_COPULA`) — 나머지는 끝이다.
 */
const COPULA = [
  "이다",
  "이고",
  "이며",
  "이면",
  "이므로",
  "이니",
  "이니까",
  "이어서",
  "이어야",
  "이어도",
  "이라",
  "이라고",
  "이라는",
  "이라면",
  "이라서",
  "이라도",
  "이란",
  "이지만",
  "이면서",
  "이거나",
  "이려면",
  "이기",
  "이자",
  "이었다",
  "이었고",
  "이었을",
  "이었다면",
  "이었습니다",
  "이었으므로",
  "인",
  "인데",
  "인가",
  "일",
  "입니다",
  "입니까",
  "였다",
  "였고",
  "였을",
  "였습니다",
  "라",
  "라고",
  "라는",
  "라면",
  "라서",
  "란",
] as const;
/** 명사처럼 쓰이는 서술격 — «인지는» · «임을». */
const NOUN_COPULA = ["인지", "임"] as const;
/** 범위 보조사 뒤에 서는 부사격 — «까지로» · «만으로» · «까지에서» · «만보다». */
const RANGE_ADVERBIAL = ["로", "으로", "에", "에서", "보다"] as const;

/** 식 뒤에 붙는 조각 전부(조사 · 서술격). */
export const MATH_PARTICLE_PIECES: readonly string[] = [
  ...new Set<string>([
    ...CLOSING_CASE,
    ...CLOSING_AUX,
    ...ADVERBIAL,
    ...RANGE_AUX,
    ...COPULA,
    ...NOUN_COPULA,
  ]),
];

/** 식과 조사를 잇는 글자 — WORD JOINER. 폭이 없고, 앞뒤 어디서도 줄을 안 바꾼다(UAX #14 LB11). */
export const MATH_PARTICLE_JOINER = "⁠";

/** 긴 조각부터 — 정규식의 고르기는 앞에서부터라 «이므로» 가 «이» 에 먹히지 않게. */
const alt = (pieces: readonly string[]) =>
  `(?:${[...pieces].sort((a, b) => b.length - a.length).join("|")})`;
const ENDING = alt([...CLOSING_CASE, ...CLOSING_AUX]);
const COPULA_WORD = `(?:${alt(COPULA)}|${alt(NOUN_COPULA)}${ENDING}?)`;
const ADVERBIAL_WORD = `${alt(ADVERBIAL)}(?:${alt([...CLOSING_AUX, "의", "와", "과"])}|${alt(RANGE_AUX)}${alt([...CLOSING_AUX, "의"])}?)?`;
const RANGE_WORD = `${alt(RANGE_AUX)}(?:${ENDING}|${alt(RANGE_ADVERBIAL)}${alt(CLOSING_AUX)}?|${COPULA_WORD})?`;

/** 낱말 전체가 겹침 규칙대로 이어진 조사 · 서술격이다(머리말 «겹침 규칙»). */
const PARTICLE_WORD = new RegExp(
  `^(?:${ENDING}|${COPULA_WORD}|${ADVERBIAL_WORD}|${RANGE_WORD})$`,
);

/** 식 뒤 한글 덩어리 — 조사 · 서술격 낱말은 길어야 대여섯 자다(«까지이므로» · «이었습니다»). 넘으면 조사 낱말이 아니다. */
const LEADING_WORD = /^[가-힣]{1,12}(?![가-힣])/;

/**
 * 이 글이 **식 바로 뒤에 붙은 조사 · 서술격**으로 시작하는가 — 렌더러가 식과 그 낱말을 잇는 판정이다.
 * 앞에 빈칸이 있으면 아니다(«$3$ 이상» — 띄어 쓴 자리는 원래 줄을 바꿔도 되는 자리다).
 * ⚠️ 생성기가 빈칸을 지우는 근거로 그대로 쓰지 않는다 — 머리말 «같은 글자가 둘».
 */
export function startsWithMathParticle(text: string): boolean {
  const word = LEADING_WORD.exec(text);
  return word !== null && PARTICLE_WORD.test(word[0]);
}
