import type { CubeLesson, CubeTask, CubeOperation } from "./types";

function model(
  id: string,
  title: string,
  a: number,
  b: number,
  operation: CubeOperation,
  pages: number[],
): CubeTask {
  return {
    id,
    kind: "regroup",
    title,
    a,
    b,
    operation,
    sourcePages: pages,
    instruction:
      operation === "add"
        ? "수 모형을 작업판으로 옮기세요. 같은 자리 10개를 한 묶음으로 바꾸고 세로셈을 완성하세요."
        : "빼야 할 만큼 수 모형을 치우세요. 모자라는 자리는 왼쪽 묶음 하나를 풀어서 계산하세요.",
    hint: "낱개 10개 = 십 묶음 1개, 십 묶음 10개 = 백 묶음 1개예요. 묶음을 바꾸어도 전체 값은 같아요.",
    explanation:
      a +
      (operation === "add" ? " + " : " − ") +
      b +
      " = " +
      (operation === "add" ? a + b : a - b) +
      ". 묶음을 바꾸는 과정이 세로셈의 작은 숫자와 연결돼요.",
  };
}
function question(
  id: string,
  title: string,
  instruction: string,
  answer: string,
  pages: number[],
  explanation: string,
  visual?: Extract<CubeTask, { kind: "question" }>["visual"],
): CubeTask {
  return {
    id,
    kind: "question",
    title,
    instruction,
    sourcePages: pages,
    fields: [{ id: "answer", label: "답", answer }],
    hint: "수를 자릿값으로 나누거나, 전체와 부분의 관계를 생각해 보세요.",
    explanation,
    visual,
  };
}
function why(
  id: string,
  title: string,
  instruction: string,
  labels: string[],
  correct: number,
  pages: number[],
  explanation: string,
): CubeTask {
  return {
    id,
    kind: "question",
    title,
    instruction,
    sourcePages: pages,
    choices: labels.map((label, i) => ({ label, value: String(i) })),
    correctChoice: String(correct),
    hint: "묶음을 바꾸기 전과 후의 전체 값은 같아야 해요.",
    explanation,
  };
}
