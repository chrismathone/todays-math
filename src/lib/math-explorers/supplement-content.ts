function parse(row: string): SupplementCard {
  const [
    unit,
    kind,
    id,
    name,
    template,
    wrong1,
    wrong2,
    question,
    yes,
    no,
    trap,
    truth,
    explanation,
    prerequisites = "",
  ] = row.split("|");
  const matches = [...template!.matchAll(/\{([^}]+)\}/g)];
  if (matches.length !== 2) throw new Error(`Invalid supplement blanks: ${id}`);
  return {
    id: id!,
    unit: unit!,
    kind: kind as ConceptKind,
    name: name!,
    definition: template!.replace(/[{}]/g, ""),
    pieces: template!.split(/\{[^}]+\}/),
    words: [matches[0]![1]!, matches[1]![1]!, wrong1!, wrong2!],
    exampleTitle: question!,
    examples: [
      ...yes!.split(" / ").map((text) => ({ text, yes: true })),
      ...no!.split(" / ").map((text) => ({ text, yes: false })),
    ],
    trap: trap!,
    truth: truth === "T",
    explanation: explanation!,
    note: explanation!,
    prerequisites: prerequisites ? prerequisites.split(",") : [],
  };
}

export const supplementCards: readonly SupplementCard[] = rows
  .trim()
  .split("\n")
  .map(parse);

export function supplementCard(id: string): SupplementCard {
  const card = supplementCards.find((item) => item.id === id);
  if (!card) throw new Error("보충 카드를 찾을 수 없어요.");
  return card;
}
