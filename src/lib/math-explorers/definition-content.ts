// Core-concept quests: grouped learning routes, not a replacement for a full textbook.
export type CourseUnit = {
  id: string;
  grade: number;
  title: string;
  symbol: string;
  subtitle: string;
  color: "blue" | "mint" | "purple";
};
export type CourseCard = {
  id: string;
  unit: string;
  name: string;
  definition: string;
  pieces: string[];
  words: string[];
  exampleTitle: string;
  examples: { text: string; yes: boolean }[];
  trap: string;
  truth: boolean;
  explanation: string;
  note: string;
  prerequisites?: string[];
};
export const courseUnits: CourseUnit[] = [];
export const courseCards: CourseCard[] = [];
// A row supplies the definition's two key words, alternatives, examples and a boundary case.
// Braces mark answer blanks. " / " separates choices without splitting fraction notation.
function unit(
  grade: number,
  id: string,
  title: string,
  symbol: string,
  rows: string,
) {
  const colors = ["blue", "mint", "purple"] as const;
  courseUnits.push({
    id,
    grade,
    title,
    symbol,
    subtitle: `${grade < 7 ? "초" + grade : "중" + (grade - 6)} · 핵심 개념 5개`,
    color: colors[courseUnits.filter((u) => u.grade === grade).length % 3],
  });
  for (const row of rows.trim().split("\n")) {
    const [
      key,
      name,
      template,
      wrong1,
      wrong2,
      question,
      yes,
      no,
      trap,
      truth,
      explanation,
      prerequisites = "",
    ] = row.split("|");
    const matches = [...template.matchAll(/\{([^}]+)\}/g)];
    if (matches.length !== 2) throw new Error(`Invalid concept blanks: ${key}`);
    const pieces = template.split(/\{[^}]+\}/),
      words = [matches[0][1], matches[1][1], wrong1, wrong2];
    courseCards.push({
      id: key,
      unit: id,
      name,
      definition: template.replace(/[{}]/g, ""),
      pieces,
      words,
      exampleTitle: question,
      examples: [
        ...yes.split(" / ").map((text) => ({ text, yes: true })),
        ...no.split(" / ").map((text) => ({ text, yes: false })),
      ],
      trap,
      truth: truth === "T",
      explanation,
      note: explanation,
      prerequisites: prerequisites ? prerequisites.split(",") : [],
    });
  }
}
