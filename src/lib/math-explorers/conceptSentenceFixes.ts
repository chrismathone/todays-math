/** 보정 칸을 덮은 카드(보정이 없으면 그대로). 원본 카드 객체는 바꾸지 않는다. */
export function applyCardFix<T extends CourseCard>(card: T): T {
  const fix = Object.hasOwn(cardFixes, card.id)
    ? cardFixes[card.id]
    : undefined;
  return fix ? { ...card, ...fix } : card;
}

