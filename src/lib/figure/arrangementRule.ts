/**
 * 「그림 없이 **배치가 정해지는가**」를 판정하는 규칙 — 원장님 지적 2026-08-25.
 *
 * ## 왜 새 규칙인가 — 기존 판정기는 이 부류를 **구조적으로 못 본다**
 *
 * `missingFigureRule.ts` 의 열쇠는 **「본문이 지면의 그림을 «가리키는가»」**다
 * (「다음 그림과 같이」·「오른쪽 상자그림에서」…). 원장님이 짚으신 문항은
 * **지시어가 하나도 없다** — 도형 배치를 그냥 말로 서술한다.
 *
 *   `J30303-A08-002` 두 직사각형 $ABCD$와 $BCFE$는 닮은 도형이고 $\square AEFD$는
 *   정사각형이다. $\overline{AB}=8$일 때, $\overline{AD}$의 길이를 구하시오.
 *
 * 점 $E$·$F$ 가 **어디에 붙는지**를 발문이 안 적는다. 해설은 $\overline{AE}=t$,
 * $\overline{BE}=8-t$ 를 전제하는데, 그 관계는 「$E$ 가 변 $AB$ 위에 있다」를 알아야
 * 나온다. 실제로 `classifyFigure()` 에 그 본문을 넣으면 **`미분류`** 다.
 * 그래서 열쇠를 **「가리키는가」에서 「정해지는가」로** 바꿨다.
 *
 * ## 축이 둘인 이유 — 한 축은 원장님 문항을 구조적으로 못 본다
 *
 * ㉠ **얽힘 축**(이 파일) : 부분이 여럿 얽히는데 배치를 고정하는 말이 없다.
 * ㉡ **형제 축**(`probe-figure-dependent.ts`) : 같은 단원의 형제 갈래는 그림을
 *    받는데 이 갈래만 못 받았다. 참을 그 행이 아니라 **이웃**에서 가져오므로
 *    낱말 목록에 기대지 않는다.
 *
 * ⚠️ **㉡ 만으로는 원장님 문항을 영영 못 잡는다.** 그 단원(`중3|3. 이차방정식|
 * 이차방정식의 활용`)은 **16행 전부 그림이 없어서** 「형제가 그림을 받는다」가
 * 성립할 수 없다 — 실측으로 확인했다. 축 하나로 줄이지 말 것.
 *
 * ## 어휘를 어떻게 골랐나 — 손으로 짓지 않았다
 *
 * 아래 낱말은 **대상 모집단의 census 에서** 골랐다(`_nofig-a11.mjs` 가 그림 없는
 * 뼈대 1,090개에서 한글 낱말 1,899종을 빈도순으로 뽑았다). 「무엇이 얽힘인지」를
 * 미리 정하고 시작하면 목록에 없는 부류는 구조적으로 0이 된다
 * (CLAUDE.md 2026-08-18 「목록을 손으로 쓰면 세는 쪽과 고치는 쪽이 같이 눈이 먼다」).
 *
 * ## 이 규칙은 **잠그지 않는다**
 *
 * 산출은 「사람이 볼 목록」이다. 실측 오탐이 적지 않다(아래 §오탐). 파괴적 처리에
 * 그대로 물려받지 말 것 — 반증하려고 넓힌 모집단을 처리 대상으로 쓴 전례가 있다
 * (CLAUDE.md 2026-08-18 「43이 433」).
 */

/**
 * **얽힘** — 부분이 둘 이상 서로 얽히거나, 한 부분을 손대서 배치가 생긴다.
 * 이 말이 없으면 배치라는 것이 아예 없으므로 「그림 없이 정해지나」를 물을 수 없다.
 *
 * census 근거(그림 없는 뼈대 1,090개 기준 등장 횟수):
 *   닮은 2 · 합동 4 · 내접 1 · 꼭 맞게 12 · 둘러싸 1 · 접 5 · 겹치 2 · 잘라 4 ·
 *   오려 1 · 붙여 2 · 귀퉁이 2 · 길을 6 · 폭이 6 · 늘이 2 · 이웃한 3 · 마주 보는 3 ·
 *   쌓 6 · 순서대로 1
 *
 * ⚠️ **조각 셋은 오늘 풀에서 한 번도 안 문다** — `닮음`·`접은`·`겹쳐`(2026-08-25 실측,
 *    `probe-figure-dependent.ts --tokens`). 활용형 변이라 앞으로 나올 수 있어 남겨
 *    두지만, **「이만큼 덮는다」를 이 셋에 기대어 말하지 말 것.** 그리고 조각을 하나씩
 *    **빼 보는** 방식으로는 이것을 못 잰다 — 두 조각이 같은 행을 물면 서로 가려
 *    둘 다 「죽음」으로 찍힌다. `--tokens` 는 「매치」와 「유일 원인」을 따로 센다.
 */
export const ENTANGLED =
  /닮은|닮음|합동|내접|외접|꼭\s*맞게|둘러싸|접었|접은|접힌|접는\s*선|접어|겹치|겹쳐|잘라|잘랐|잘린|자른|오려|붙여|붙인|붙였|귀퉁이|길을\s*내|길의|폭이|늘이|늘였|줄여|이웃한|마주\s*보는|쌓기나무|쌓았|쌓아|쌓은/;

/**
 * **꼭짓점 이름으로 정의된 도형이 둘 이상**이고 글자를 나눠 쓴다.
 * 원장님 문항의 모양이다 — `ABCD` 와 `BCFE` 가 `B`·`C` 를 공유한다.
 * 한 덩어리만 있으면(`직각삼각형 ABC`) 그 자체로 배치가 정해지므로 얽힘이 아니다.
 *
 * ⚠️ 수식 명령(`\square`·`\mathrm`)을 먼저 지운다 — 안 지우면 `\square AEFD` 의
 *    `AEFD` 를 놓치고, `\mathrm` 의 대문자 없는 덩어리를 라벨로 오인하지도 않는다.
 */
export function sharedVertexShapes(content: string): string[] {
  const stripped = content.replace(/\\[A-Za-z]+/g, " ");
  const labels = [
    ...new Set(stripped.match(/(?<![A-Za-z])[A-Z]{3,5}(?![A-Za-z])/g) ?? []),
  ];
  if (labels.length < 2) return [];
  // 글자를 하나라도 나눠 쓰는 짝이 있어야 «서로 얽힌» 것이다.
  const shares = labels.filter((a) =>
    labels.some((b) => a !== b && [...a].some((ch) => b.includes(ch))),
  );
  return shares.length >= 2 ? shares : [];
}

/**
 * **배치를 고정하는 말** — 이것이 있으면 그림이 없어도 배치가 정해진다.
 * 전량 눈으로 확인한 사례에서 뽑았다(각 항목의 실제 문항은 아래 주석).
 *
 * · `(단, …)`      : 「단, 정육각형의 여섯 꼭짓점은 모두 원 위에 있습니다」(`E61101-A04`)
 * · 방향·개수 명시 : 「가로 방향과 세로 방향으로 하나씩」(`J30201-A09`) ·
 *                    「네 귀퉁이에서 … 각각」(`J30303-A07`) · 「가로로 2개, 세로로 3개씩」
 * · 순서 명시      : 「네 점 A, B, C, D가 **이 순서대로**」(`J30603-A09`)
 * · 모양 명시      : 「폭이 일정한 **십자 모양의** 길」(`J30303-A06-002`) — 같은 갈래의
 *                    형제 행(`-001`)은 이 말이 **없다.** census 에서 `십자` 는 **1회**
 *                    뿐이었고, 그 1회가 곧 「형제는 적는데 이 행만 안 적는다」의 증거다.
 * · 좌표           : 「네 점 $\mathrm{A}(-2, -6)$, …」(`J20408-A09`)
 * · 각도로 고정    : 「$\angle B=90^\circ$」 — 직각삼각형은 각이 배치를 정한다
 */
export const PINNED =
  /\(\s*단[,，]|이\s*순서대로|가로\s*방향과\s*세로\s*방향|네\s*귀퉁이|가로로\s*\$?\d|세로로\s*\$?\d|각각|차례로|십자\s*모양|\(\s*-?\d+\s*,\s*-?\d+\s*\)|좌표가|angle\s*[A-Z]+\s*=|=\s*90\^?\\?circ|수직인/;

export type ArrangementVerdict = "배치미정" | "배치확정" | "얽힘없음";

/**
 * 발문 하나를 판정한다. **그림이 없는 행에만 쓴다** — 그림이 붙어 있는 행에 대고
 * 물으면 「배치미정」이 「그래서 그림을 그렸다」는 뜻이 되어 답이 뜻을 잃는다.
 *
 * ⚠️ `배치미정` 은 **「못 푼다」가 아니라 「사람이 봐야 한다」**다. 실측으로
 *    오탐이 있다 — 배치가 안 정해져도 **묻는 값이 배치와 무관**할 수 있다
 *    (`E50601-A04` 「한 귀퉁이에서 직사각형을 잘라 냈습니다 … 둘레」 — 어느
 *    귀퉁이든 둘레는 같다). 그 판정은 코드가 못 하므로 사람이 한다.
 */
export function classifyArrangement(content: string): ArrangementVerdict {
  const c = content.replace(/\s+/g, " ");
  const entangled = ENTANGLED.test(c) || sharedVertexShapes(c).length > 0;
  if (!entangled) return "얽힘없음";
  return PINNED.test(c) ? "배치확정" : "배치미정";
}
