/**
 * **문항의 수치(cm)를 지면 단위로 옮기는 배율** — 한 곳에 둔다.
 *
 * 🔴 **배율을 갈래마다 손으로 정하면 «수치가 작은 문항»이 지면에서 사라진다.**
 *    실측 2026-08-28 — 아르벨로스는 배율이 **아예 없어** 도형 지름이 14단위인데
 *    라벨 글자가 24단위였다(**글자가 도형보다 크다**). 직사각형은 `SCALE=4` 라
 *    20×16, 피타고라스 갈래는 `Math.min(14, 170/…)` 라 3-4-5 삼각형이 70단위였다.
 *    RPM 정본은 「라벨 글자 ÷ 도형 선 길이 = 10.2%」, 즉 **도형이 글자의 열 배쯤**이다
 *    (`docs/planning/tracks/reports/rpm-engine-gaps.md` ①·②).
 *
 * ⚠️ **상한(`Math.min`)을 두지 마라.** 상한은 큰 수치일 때만 안 걸리므로, 작은
 *    수치의 그림만 조용히 작아진다 — 그리고 **에러가 안 난다.** 상한 없이 쓰면
 *    가장 긴 치수가 늘 `target` 이 되는데, 그 크기는 이미 큰 수치에서 나오던 값이라
 *    새로 커지는 그림은 없다.
 *
 * ⚠️ `longest` 가 0 이면 나눗셈이 무한대가 된다. 상한이 그것을 **우연히** 막고
 *    있었으므로, 상한을 걷어내는 자리에서는 여기서 막는다.
 *
 * 「도형 지름 ÷ 글자 크기」는 `scripts/qa/probe-middle-label-outward.ts` 가 잰다.
 */
export function drawScale(longest: number, target = 150): number {
  return longest > 0 ? target / longest : 1;
}
