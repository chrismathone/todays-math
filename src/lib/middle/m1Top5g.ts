/**
 * 첫 조건이 만드는 후보 — $c_1$ 과의 차의 절댓값이 $d_1$ 이하인 정수 전부.
 *
 * 이 목록은 **자료가 아니라 우리가 만든 것**이라 오름차순이 곧 정의다(㉵ 의
 * 「정렬이 순위를 암시한다」가 여기서는 성립하지 않는다).
 */
export function absoluteWindowCandidates(c1: number, d1: number): number[] {
  if (!Number.isInteger(c1) || !Number.isInteger(d1) || d1 < 1) {
    throw new Error(`absoluteWindowCandidates: 창이 이상하다 — ${c1}, ${d1}`);
  }
  const out: number[] = [];
  for (let v = c1 - d1; v <= c1 + d1; v += 1) out.push(v);
  return out;
}

/**
 * 🔴 **여기서도 굳지 않는다.**
 *
 * 첫 조건은 후보를 유한하게 만들어 줄 뿐이고, 어느 후보가 살고 죽는지는 **하나씩
 * 두 번째 조건에 대 봐야만** 안다. 살아남는 것이 한 덩어리인지 두 덩어리인지도
 * 미리 알 수 없다(D-115 ⑾ 의 «상»).
 *
 * ⚠️ 이 함수는 **굳힘을 인자로 받는다** — 두 번째 조건을 흔들면 살아남는 것이
 *    달라져야 한다(㉡). 두 창이 안 겹치면 **하나도 안 남는다**(음성 대조).
 */
export function absoluteWindowSurvivors(
  c1: number,
  d1: number,
  c2: number,
  d2: number,
): number[] {
  return absoluteWindowCandidates(c1, d1).filter((v) => Math.abs(v - c2) >= d2);
}

/** 살아남은 것이 이어진 덩어리 몇 개인가 — ㉠ 축(자리가 한쪽 끝만인가). */
export function survivorBlocks(alive: readonly number[]): number {
  let blocks = 0;
  for (let i = 0; i < alive.length; i += 1) {
    if (i === 0 || alive[i]! !== alive[i - 1]! + 1) blocks += 1;
  }
  return blocks;
}

/**
 * 두 수의 차를 지면 글자로 — 큰 수에서 작은 수를 빼되 음수는 괄호로 싼다.
 *
 * 🔴 **작은 쪽이 $0$ 이면 뺄셈을 적지 않는다.** `$3-0=3$` 은 값이 맞지만
 * 지면 냄새(`pageSmells` 의 「상수 $0$ 을 더했다」 — `[+-]0` 을 문다)라
 * `null` 을 내고, 부르는 쪽이 뺄셈 없는 문장으로 적는다. 실측으로 씨앗
 * 660판 중 **118판**이 이 자리에서 걸렸다(고치기 전).
 */
export function differenceTex(u: number, v: number): string | null {
  const hi = Math.max(u, v);
  const lo = Math.min(u, v);
  if (lo === 0) return null;
  return lo < 0 ? `${hi}-(${lo})` : `${hi}-${lo}`;
}

