        // 🔴 ㉡ 두 번째 조건을 흔들면 살아남는 것이 달라져야 한다.
        //    잃은 것(창 전수, D-20) — 판 **2,094 → 2,094**(0.00%) ·
        //    서로 다른 답 **185 → 185**. ⚠️ **실측 걸림 0건**이지만 «못 셈»이 아니다 —
        //    바로 위 「후보합」 가드를 **넣기 전에는 이 줄이 18판을 걸렀다**(2,180 →
        //    2,162). 그 18판을 후보합 가드가 먼저 가져갔을 뿐이고, 후보합을 무르면
        //    이 줄이 다시 일한다. 시험이 그 사실을 손으로 만든 판으로 확인한다.
        //    남은 것: **2,094판 · 서로 다른 답 185 · 최빈 2.15%**.
        const shaken = absoluteWindowSurvivors(c1, d1, c2, d2 + 1);
