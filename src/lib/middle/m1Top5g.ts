/**
 * 🔴 **굳힘은 이 소단원의 개념 「(시간)$=$(거리)$\div$(속력)」 하나다.**
 *
 * 약속한 시각까지 남은 시간 $t$ 는 발문에 없다. 그런데 거리를 $x$ 라 하면
 * $\dfrac xa=t+p$ 와 $\dfrac xb=t-q$ 가 서고, **두 식의 차에서 $t$ 가 저절로 없어져**
 * $\dfrac xa-\dfrac xb=p+q$ 하나가 남는다 — $t$ 를 하나씩 넣어 보는 걸음이 없다
 * (D-115 ⑾ 의 «중»).
 *
 * ⚠️ 이 함수는 **굳힘을 인자로 받는다** — 네 수 중 어느 것을 흔들어도 거리가
 *    달라져야 한다(㉡). 거리가 정수가 아니면 `null` 이다(음성 대조).
 */
export function travelDistance(
  a: number,
  b: number,
  p: number,
  q: number,
): number | null {
  if (!(b > a) || a <= 0 || p <= 0 || q <= 0) return null;
  const numer = a * b * (p + q);
  const den = b - a;
  if (numer % den !== 0) return null;
  return numer / den;
}

/** 최소공배수 — 양변에 곱할 수. `gcd` 는 `m1Top.ts` 것을 읽어만 온다. */
function lcm2(a: number, b: number): number {
  return (a / gcd(a, b)) * b;
}

