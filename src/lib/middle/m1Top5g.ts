/** $n$각형의 대각선의 개수 — 한 꼭짓점에서 $n-3$개씩, 두 번 세었으므로 절반. */
export function polygonDiagonals(n: number): number {
  if (!Number.isInteger(n) || n < 3) {
    throw new Error(
      `polygonDiagonals: 변이 셋 이상인 다각형이어야 한다 — ${n}`,
    );
  }
  return (n * (n - 3)) / 2;
}

/**
 * 해설이 $m$ 을 어디까지 훑어야 하나 — $m<n$ 을 지키는 마지막 자리.
 *
 * $m<n=S-m$ 은 곧 $m<\dfrac S2$ 이므로 $\lfloor(S-1)/2\rfloor$ 이 마지막이다.
 * 🔴 ㉴ 이 값이 곧 「지면이 자기가 세운 제약을 지키는가」의 잣대다 — 해설은
 * **이 자리를 넘어가지 않고**, 멈추는 근거도 그 제약 자체다.
 */
export function lastSideToCheck(s: number): number {
  return Math.floor((s - 1) / 2);
}

/**
 * 🔴 **여기서는 굳지 않는다.**
 *
 * 변의 개수의 합 $S$ 와 대각선의 개수의 합 $D$ 가 있어도 두 다각형은 한 번에 안
 * 나온다. $m+n=S$ 와 $\dfrac{m(m-3)}2+\dfrac{n(n-3)}2=D$ 를 함께 푸는 길은 이차방정식
 * 이라 중1에 없으므로, $m=3,4,5,\dots$ 을 차례로 놓고 그때마다 대각선의 개수의 합을
 * **실제로 세어 $D$ 와 견주어야** 한다(D-115 ⑾ 의 «상»).
 *
 * ⚠️ 이 함수는 **굳힘을 인자로 받는다** — $D$ 를 흔들면 짝이 달라지거나 없어져야 한다(㉡).
 *    그 자가 «아니오»를 낼 수 있음은 시험이 「어떤 짝도 없는 $(S,D)$」로 보인다.
 *
 * 짝이 **정확히 하나**일 때만 그 짝을 내고, 없거나 둘 이상이면 `null` 이다
 * (실제로는 $S$ 가 정해지면 $mn$ 도 정해져 짝이 둘일 수 없다 — 그 사실을 여기서
 * 가정하지 않고 **세어서** 확인한다).
 */
export function sidePairFromSums(
  s: number,
  d: number,
): [number, number] | null {
  const found: [number, number][] = [];
  const stop = lastSideToCheck(s);
  for (let m = 3; m <= stop; m += 1) {
    const n = s - m;
    if (n < 3) continue;
    if (polygonDiagonals(m) + polygonDiagonals(n) === d) found.push([m, n]);
  }
  return found.length === 1 ? found[0]! : null;
}

/**
 * 「대각선 조건을 안 보고 그냥 반씩 나눈」 학생의 답 — 판정기의 `withoutBinding` 축.
 *
 * 이 값이 참 답과 같아지는 판은 생성기가 버린다. 그래야 굳힘이 «어느 후보인가»를
 * 실제로 고른다는 것이 재는 형태가 된다.
 */
export function halvedSideProduct(s: number): number {
  const m = lastSideToCheck(s);
  return m * (s - m);
}

