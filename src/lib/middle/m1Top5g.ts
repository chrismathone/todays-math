        // 🔴 ㉵ 지면에 찍히는 수는 $c_1$·$d_1$·$c_2$·$d_2$ 넷이다.
        //    잃은 것(창 전수, D-20) — 판 **2,312 → 2,094**(9.43%) ·
        //    서로 다른 답 **186 → 185**.
        //    ⚠️ **이 자는 여기서 힘이 약하다.** 우연 수준(답을 판끼리 돌려 끼운 널 모형
        //    3회)이 **8.15%** 라 9.43% 는 우연의 **1.16배**뿐이다. 지면에 수가 넷이고
        //    그중 둘이 음수라 도달 가능한 값이 원래 많다. 「9.43%가 걸렸으니 이 유형이
        //    뻔하다」로 읽어도, 「걸러 냈으니 깨끗하다」로 읽어도 안 된다 — 이 유형의
        //    판별력은 위 ㉠ 축(어느 후보가 살아남는가)이 든다.
