/** 목록을 `$1$, $2$, $3$` 꼴로. */
function listTex(xs: readonly number[]): string {
  return xs.map((v) => `$${v}$`).join(", ");
}

/**
 * 수를 이어 더한 식 — `$-11-10-9-8$` 처럼 **`+-` 가 안 생기게** 잇는다.
 *
 * 🔴 음수를 그냥 `+` 로 이으면 지면에 `-11+-10` 이 나가고, 그것은 값 검산으로는
 * 안 잡히는 **지면 냄새**다(`pageSmells` 의 「`+-` 나 `--` 가 붙었다」).
 * $0$ 은 `+0` 이 되어 또 다른 냄새를 만들므로 **생성기가 $0$ 이 든 판을 아예 버린다.**
 */
export function sumTex(xs: readonly number[]): string {
  if (xs.length === 0) throw new Error("sumTex: 더할 것이 없다");
  return xs
    .map((v, i) => {
      if (v === 0) throw new Error("sumTex: $0$ 은 `+0` 냄새를 만든다");
      if (i === 0) return String(v);
      return v > 0 ? `+${v}` : String(v);
    })
    .join("");
}

