          const head =
            diff === null
              ? `$a=${v}$이면 $${v}$${waGwa(v)} $${c2}$의 차의 절댓값은 $${dist}$이고`
              : `$a=${v}$이면 $${diff}=${dist}$이므로 차의 절댓값은 $${dist}$이고`;
