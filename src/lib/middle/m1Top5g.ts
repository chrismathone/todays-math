/**
 * 🔴 **굳힘은 「(정가)$=$(원가)$+$(이익)」과 「(판매가)$=$(정가)$-$(할인액)」이다.**
 *
 * 원가도 정가도 모르지만, 원가를 $x$ 라 두면 두 조건이 **같은 정가**를 각각
 * $x+\dfrac{r_1}{100}x+d_1$ 과 $x+\dfrac{e_2}{100}x+d_2$ 로 나타낸다. **정가는
 * 하나뿐**이라는 사실이 두 식을 등식으로 묶어 일차방정식 하나가 되므로, 정가를
 * 하나씩 넣어 보는 걸음이 없다(D-115 ⑾ 의 «중»).
 *
 * $e_2$ 는 두 번째 조건의 «이익률»이고 손해면 음수다.
 *
 * ⚠️ 두 비율이 같으면 분모가 $0$ 이 되어 원가가 **아예 정해지지 않는다** — 그것이
 *    이 자의 음성 대조다(`null`).
 */
export function costFromDiscounts(
  r1: number,
  e2: number,
  d1: number,
  d2: number,
): number | null {
  if (r1 === e2) return null;
  const numer = 100 * (d2 - d1);
  const den = r1 - e2;
  if (numer % den !== 0) return null;
  const a = numer / den;
  return a > 0 ? a : null;
}

/** 그때의 정가 — 이 유형의 정답. 원가가 안 정해지면 `null`. */
export function listPriceFromDiscounts(
  r1: number,
  e2: number,
  d1: number,
  d2: number,
): number | null {
  const a = costFromDiscounts(r1, e2, d1, d2);
  if (a === null) return null;
  if ((a * r1) % 100 !== 0) return null;
  return a + (a * r1) / 100 + d1;
}

