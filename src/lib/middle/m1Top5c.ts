/**
 * 🔴 **굳힘은 이 소단원의 개념 하나다 — 도수를 하나도 넣어 보지 않는다.**
 *
 * 히스토그램에서 각 직사각형의 가로는 **계급의 크기**, 세로는 그 계급의 **도수**이므로
 * 넓이는 둘의 곱이다. 계급의 크기가 모두 같으므로 두 직사각형의 넓이의 차는
 * (계급의 크기)와 (두 도수의 차)의 곱이고, 따라서 **도수의 차 = 넓이의 차 ÷ 계급의 크기**다.
 * 도수의 합은 도수의 총합에서 곧장 나오므로, 합과 차에서 두 값이 한 번에 나온다
 * (D-115 ⑾ 의 «중» — 후보를 «끝까지 계산하지 않고» 거른다).
 *
 * ⚠️ 이 함수는 **굳힘을 인자로 받는다** — 차를 흔들면 답이 달라져야 한다(㉡).
 *    그 자가 «아니오»를 낼 수 있음은 시험이 **홀짝이 어긋난 짝**으로 보인다(자연수 짝이 없다).
 */
export function largerFromSumAndDiff(sum: number, diff: number): number | null {
  if (!Number.isInteger(sum) || !Number.isInteger(diff)) return null;
  if (diff < 0 || diff > sum) return null;
  if ((sum + diff) % 2 !== 0) return null;
  const big = (sum + diff) / 2;
  const small = sum - big;
  if (small < 1) return null;
  return big;
}

