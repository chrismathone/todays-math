/**
 * 🔴 **여기서는 굳지 않는다.**
 *
 * $a$각기둥(또는 $a$각뿔대)은 꼭짓점이 $2a$, 모서리가 $3a$, 면이 $a+2$ 이고,
 * $b$각뿔은 꼭짓점이 $b+1$, 모서리가 $2b$, 면이 $b+1$ 이다. 꼭짓점의 개수의 합이
 * 주어지면 $b=K-2a$($K=$ 합$-1$)라는 **일차식**이 서지만, 모서리의 개수의
 * **최대공약수** $\gcd(3a,\ 2b)$ 는 $a$ 에 대해 **닫힌 식으로 못 푼다.**
 * 그러므로 $a=3,4,5,\dots$ 를 차례로 놓고 그때마다 두 수를 구해 최대공약수를
 * **실제로 계산해 견줘야** 한다(D-115 ⑾ 의 «상»).
 *
 * 끝나는 근거조차 계산이 아니라 **견줌**이다 — $b$ 가 $3$ 보다 작아지면 밑면이
 * 다각형일 수 없다.
 *
 * ## 🔴 왜 «곱»이 아니라 «최대공약수»인가 (2026-09-04, D-116 5차)
 *
 * 종전에는 둘째 조건이 모서리의 개수의 **곱** $6ab$ 였다. 그런데 $6a(K-2a)$ 는
 * $a=K/4$ 에서 최대인 **위로 볼록**한 함수라 $a$ 와 $K/2-a$ 가 **같은 곱**을 낸다.
 * 그래서 「답이 하나로 정해진다」는 가드가 **첫쪽 후보를 골라 버리고 끝쪽만 남겼다** —
 * 창 전수에서 자리별 통과율이 $a=3$ **19.4%** 부터 $a=9$ **100.0%** 까지 단조로
 * 올랐고, 살아남는 $a$ 가 **훑기의 끝 자리인 판이 48.2%** 였다. 「끝에서부터
 * 훑으면 첫 줄에 끝난다」는 뜻이라 «후보를 다 만들어 견준다»가 무너진다.
 *
 * 창을 깎는 길(끝 자리 버리기·양끝 버리기·$K$ 홀수만)은 전부 **쏠림을 옆으로
 * 옮길 뿐**이었다(끝을 막으면 둘째 후보가 16.9% → 32.6%). 자리를 **먼저 뽑아
 * 되푸는** 길도 안 들었다 — $(a,b)$ 와 $(K,a)$ 는 일대일 대응이라 통과 집합이
 * 그대로이기 때문이다. 뿌리는 **버리는 규칙이 답의 자리를 본다**는 것이었다.
 *
 * 최대공약수는 볼록하지 않아 그 규칙이 자리와 무관해진다. 창 전수 실측:
 *
 * | | 곱(종전) | **최대공약수(지금)** |
 * |---|---|---|
 * | 자리별 통과율 | 19.4 → 35.0 → 47.5 → 40.6 → 50.0 → 62.5 → **100.0%** (단조) | 38.9 → 60.0 → 47.5 → 62.5 → 33.3 → 68.8 → 0.0% (**단조가 아니다**) |
 * | 참 자리의 상대 위치 중앙값 | **0.833** | **0.500** |
 * | 지름길 — 첫/둘째/끝둘째/끝 | 8.4 / 16.9 / 12.0 / **48.2%** | 14.6 / 25.0 / 26.0 / 19.8% |
 * | 가장 잘 뚫는 고정 자리 | 뒤1째 **48.2%** (우연의 **2.46배**) | 뒤2째 **26.0%** (우연의 **1.34배**) |
 * | 창 · 서로 다른 답 · 최빈 정답 | 83 · 41 · 7.2% | **96 · 52 · 5.2%** |
 *
 * ⚠️ 위 「96 · 52」는 **약수 가드를 넣기 전** 값이다. 최대공약수로 바꾸자 새 축이
 *    하나 드러났다 — $V\mid 3a$ 이므로 학생이 훑기 전에 후보를 줄일 수 있고,
 *    그것이 후보를 **하나로** 줄이는 판이 **26.0%** 였다(그 줄이기 자체는 지름길이
 *    아니다 — 우연의 1.01배). 그 판을 버리는 가드를 더해 최종 창은
 *    **71판 · 서로 다른 답 47 · 최빈 정답 5.6%** 이고, 고정 자리 지름길은
 *    **1.34배 → 1.41배**로 조금 오른다. 자세한 것은 그 가드의 주석에 적었다.
 *
 * ⚠️ **1.34배는 «지름길이 없다»가 아니라 «우연보다 크게 낫지 않다»는 뜻이다.**
 *    후보가 평균 다섯뿐이라는 사실은 그대로여서 고정 자리 하나가 여전히 우연히
 *    19.5% 를 맞는다. 다음 사람이 그것을 알아야 한다.
 *
 * ⚠️ **배수가 낮다고 심화상인 것이 아니다.** 대조로 잰 「모서리의 개수의 **합**」은
 *    배수가 **1.30** 으로 가장 낮은데 $3a+2b=2K-a$ 라 $a=2K-S$ 로 **곧장 풀린다** —
 *    훑을 것이 없으니 심화상이 아니다. 「가장 잘 뚫는 자리가 낮다」는 «자리가 고르다»는
 *    뜻이지 «견줘야 한다»는 뜻이 아니다. 조건을 갈아 끼울 때는 **닫힌 해법이 있는가**를
 *    같이 물어야 한다.
 *
 * ⚠️ 그 자가 «아니오»를 낼 수 있음은 시험이 두 판으로 보인다 — 살아남는 $a$ 가
 *    **둘**인 판($K=21$ 에서 $\gcd=3$ 은 $a=3$ 과 $a=9$ 둘)과 **하나도 없는** 판(빈 배열).
 */
export function polyhedronScan(kSum: number, edgeGcd: number): number[] {
  const out: number[] = [];
  for (let a = 3; kSum - 2 * a >= 3; a += 1) {
    const b = kSum - 2 * a;
    if (gcd(3 * a, 2 * b) === edgeGcd) out.push(a);
  }
  return out;
}

/** 훑기를 멈추는 첫 자리 — $b$ 가 $3$ 보다 작아지는 $a$. */
export function polyhedronStop(kSum: number): number {
  let a = 3;
  for (; kSum - 2 * a >= 3; a += 1);
  return a;
}

/**
 * 🔴 **학생이 약수의 성질로 미리 줄일 수 있는 후보** — $V\mid 3a$ 인 자리들.
 *
 * $V=\gcd(3a,\ 2b)$ 이면 $V$ 는 $3a$ 의 약수다. 그러므로 학생은 훑기 전에
 * $3a$ 가 $V$ 로 나누어떨어지는 자리만 남길 수 있다(예: $V=5$ 이면 $a$ 는 $5$ 의
 * 배수뿐이다). **이것은 지름길이 아니라 올바른 풀이의 일부다** — 실측으로
 * 「거른 뒤 첫 후보를 찍는다」의 적중률은 35.2%, 그 안에서의 우연 수준은 34.9% 로
 * **1.01배**다(줄여 놓고도 어느 것인지는 여전히 견줘야 한다).
 *
 * ⚠️ **문제는 그것이 후보를 «하나»로 줄이는 판이다.** 그때는 약수 성질만으로 답이
 * 나와 「후보를 다 만들어 견준다」가 성립하지 않는다 — 이 유형이 심화상인 바로 그
 * 근거가 무너진다. 가드 없이 재면 그런 판이 **26.0%** 였다. 그래서 생성기가
 * **둘 이상 남는 판만** 낸다(아래 `divisorCandidates(...).length < 2` 가드).
 *
 * 종전(곱 조건)에도 같은 자리가 있었다 — 그때는 $3a$ 가 곱 $P$ 의 약수여야 하므로
 * 같은 방식으로 줄어들고, 견줄 것 없는 판이 **18.1%** 였다. 아무도 안 세고 있었다.
 */
export function polyhedronDivisorCandidates(
  kSum: number,
  edgeGcd: number,
): number[] {
  const out: number[] = [];
  const stop = polyhedronStop(kSum);
  for (let a = 3; a < stop; a += 1) {
    if ((3 * a) % edgeGcd === 0) out.push(a);
  }
  return out;
}

