/**
 * 🔴 **여기서도 굳지 않는다.**
 *
 * 도수의 총합에서 두 계급의 도수의 **합**은 곧장 나오지만, 둘째 조건이 **곱**이라
 * 중1 도구로는 두 값을 한 번에 못 정한다(이차방정식도 인수분해도 없다). 그러므로
 * 합이 $S$ 인 자연수 짝 $(1,\ S-1)$, $(2,\ S-2)$, $\dots$ 를 **전부 만들어** 곱을
 * 하나씩 견줘야 한다(D-115 ⑾ 의 «상»).
 *
 * ⚠️ 그 자가 «아니오»를 낼 수 있음은 시험이 **아무 짝과도 안 맞는 곱**으로 보인다
 *    (빈 값 — 지어낸 값을 내지 않는다).
 */
export function factorPairWithSum(
  sum: number,
  product: number,
): [number, number] | null {
  for (let small = 1; small * 2 <= sum; small += 1) {
    if (small * (sum - small) === product) return [small, sum - small];
  }
  return null;
}

