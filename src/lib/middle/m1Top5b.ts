/**
 * 🔴 **밑면이 $n$각형인 각뿔에서 «밑면의 모서리 하나 + 옆모서리 하나» 짝 중
 * 꼬인 위치인 것의 개수.** 값은 $n\times(n-2)$ 다.
 *
 * 근거는 **밑면의 모양과 무관**하다(정$n$각형일 필요가 없다):
 * 옆모서리 $\mathrm{V}A_i$ 는 밑면과 점 $A_i$ 에서만 만나므로 밑면 위의 어떤
 * 직선과도 평행할 수 없다. 그러니 밑면의 모서리와 **만나지 않으면 반드시 꼬인
 * 위치**다. 만나는 것은 $A_i$ 를 끝 점으로 갖는 두 개뿐이므로 옆모서리 하나마다
 * $n-2$ 개, 옆모서리가 $n$ 개이니 $n\times(n-2)$.
 *
 * ⚠️ 이 함수는 **굳힘을 인자로 받는다** — $n$ 을 흔들면 값이 달라져야 한다.
 *    $n\ge3$ 에서 **순증가**이고, 그 사실이 곧 `pyramidSideFromSkew` 의 유일성 근거다.
 */
export function skewPairCount(n: number): number {
  if (!Number.isInteger(n) || n < 3) {
    throw new Error(`skewPairCount: 밑면은 삼각형 이상이어야 합니다 — ${n}`);
  }
  return n * (n - 2);
}

