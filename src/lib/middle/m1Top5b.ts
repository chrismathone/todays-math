/** 서로 다른 값 `count` 개를 `[lo, hi]` 에서 — 못 뽑으면 `null`. */
function distinctFrom(
  rng: Rng,
  lo: number,
  hi: number,
  count: number,
): number[] | null {
  if (hi - lo + 1 < count) return null;
  const bag = new Set<number>();
  for (let guard = 0; guard < 200 && bag.size < count; guard += 1) {
    bag.add(intBetween(rng, lo, hi));
  }
  if (bag.size < count) return null;
  return [...bag].sort((a, b) => a - b);
}

