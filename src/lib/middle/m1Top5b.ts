/**
 * 🔴 **굳힘은 이 소단원의 개념 「일차식이려면 $x^{2}$ 의 계수가 $0$」이다.**
 *
 * $pa-qb=0$ 과 $a+b=S$ 를 함께 풀면 $b=pS\div(p+q)$, $a=S-b$ 다 —
 * $S-1$ 쌍의 후보를 **하나도 만들지 않고** 짝이 곧장 나온다(D-115 ⑾ 의 «중»).
 *
 * 되돌려 주는 것은 `[a, b]`. 두 값이 자연수가 아니면 **던진다** — 조용히
 * 반올림하면 지면에 자연수가 아닌 «자연수»가 나간다.
 *
 * ⚠️ 이 함수는 **굳힘을 인자로 받는다** — $p$ 나 $q$ 를 흔들면 짝이 달라져야 한다.
 *    그 자가 «아니오»를 낼 수 있음은 시험이 $p=q$ 로 보인다(그때는 $a=b$ 라
 *    $x$ 의 계수 $a-b$ 가 $0$ 이 되어 **일차식이 아니게 된다** — 굳힘이 스스로를
 *    무너뜨리는 자리라 창에서 뺐다).
 */
export function linearCoefficientPair(
  p: number,
  q: number,
  s: number,
): [number, number] {
  const b = (p * s) / (p + q);
  const a = s - b;
  if (!Number.isInteger(a) || !Number.isInteger(b) || a < 1 || b < 1) {
    throw new Error(`linearCoefficientPair: 자연수 짝이 아니다 — ${a}, ${b}`);
  }
  return [a, b];
}

/**
 * 창 — $x^{2}$ 의 계수 $pa-qb$ 의 계수 짝.
 *
 * 조건 셋: ⑴ **서로소**여야 $S$ 의 배수 조건이 $p+q$ 로 딱 떨어진다.
 * ⑵ **$p\ne q$** — 같으면 $a=b$ 라 $x$ 의 계수가 $0$ 이 되어 **일차식이 아니게 된다.**
 *    굳힘이 스스로를 무너뜨리는 자리라 창에서 뺐다(`linearCoefficientPair` 의 음성 대조).
 * ⑶ **둘 다 $2$ 이상** — $1$ 이면 지면에 「$1a$」가 나가고 `pageSmells` 의
 *    「계수 $1$ 을 적었다」가 그것을 잡는다.
 *
 * ⚠️ **두 차례를 다 넣는다**($[2,3]$ 과 $[3,2]$ 를 둘 다). $p>q$ 이면 $a<b$ 라
 *    $x$ 의 계수가 **음수**인데, 그것도 일차식이다 — 오히려 「$a-b$ 가 $0$ 이 아닌가」를
 *    「$a-b$ 가 양수인가」로 잘못 외운 학생이 여기서 갈린다. 한쪽만 넣으면 그 자리가
 *    지면에 **한 번도 안 나온다.**
 */
