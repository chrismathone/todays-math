/** 작은 것부터 늘어놓은 약수 전부. */
export function divisorsOf(n: number): number[] {
  if (!Number.isInteger(n) || n < 1) {
    throw new Error(`divisorsOf: 자연수여야 합니다 — ${n}`);
  }
  const out: number[] = [];
  for (let d = 1; d * d <= n; d += 1) {
    if (n % d !== 0) continue;
    out.push(d);
    if (d !== n / d) out.push(n / d);
  }
  return out.sort((a, b) => a - b);
}

/**
 * 🔴 **굳힘은 이 소단원의 개념 $xy=a$ 하나다 — 점을 하나도 만들지 않는다.**
 *
 * $y=\dfrac{a}{x}$ 위의 점에서는 $x\times y=a$ 이므로, $x$ 와 $y$ 가 **둘 다 자연수**
 * 이면 $x$ 는 $a$ 의 약수이고 그 짝 $y=a\div x$ 도 $a$ 의 약수다. 그리고 $x$ 가 약수
 * 전체를 훑으면 $y$ 도 **같은 집합**을 훑으므로, 점마다 $y$ 를 계산하지 않고 «약수의 합»
 * 하나로 답이 나온다(D-115 ⑾ 의 «중»).
 *
 * ⚠️ 이 함수는 **굳힘을 인자로 받는다** — $a$ 를 흔들면 답이 달라져야 한다(㉡).
 *    그 자가 «아니오»를 낼 수 있음은 시험이 $\sigma(14)=\sigma(15)=24$ 로 보인다.
 */
export function divisorSum(n: number): number {
  return divisorsOf(n).reduce((a, b) => a + b, 0);
}

/**
 * 🔴 **이 유형의 진짜 지름길** — 발문에 수가 $a$ **하나**뿐이라
 * `pageShortcutValues([a])` 는 `{a}` 밖에 못 만든다(그 자는 여기서 **구조적으로 0**이다).
 * 그래서 「$a$ 에 작은 수를 한두 번 곱하거나 나눈 값」을 따로 세어 막는다.
 *
 * 실측(창 전수 96): $\sigma(24)=60=24\div2\times5$ · $\sigma(28)=56=28\times2$ 둘이 걸린다.
 */
export function scaledValues(a: number): Set<number> {
  const step = (v: number, out: Set<number>): void => {
    for (const k of [2, 3, 4, 5, 10, 100]) {
      out.add(v * k);
      if (v % k === 0) out.add(v / k);
    }
  };
  const first = new Set<number>([a]);
  step(a, first);
  const out = new Set<number>(first);
  for (const v of first) step(v, out);
  return out;
}

/**
 * 약수가 여섯~열두 개인 수. 너무 적으면 「점이 여러 개」가 무색하고, 너무 많으면
 * 해설의 나열 줄이 길어진다(㉮). 실측: $12$~$240$ 에서 **96개**.
 */
const INVERSE_CONSTANTS: readonly number[] = (() => {
  const out: number[] = [];
  for (let a = 12; a <= 240; a += 1) {
    const k = divisorsOf(a).length;
    if (k < 6 || k > 12) continue;
    out.push(a);
  }
  return out;
})();

