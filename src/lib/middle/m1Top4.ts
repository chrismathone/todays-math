/** 상대도수 $P/100$ 을 기약분수로 볼 때의 분모. */
export function relativeDenominator(p100: number): number {
  return 100 / gcd(p100, 100);
}

/**
 * 🔴 **굳힘은 「(도수)$=$(도수의 총합)$\times$(상대도수)」 하나다.**
 *
 * 도수는 학생 수라 **자연수**이므로 $N\times\dfrac{P}{100}$ 이 자연수여야 하고,
 * 기약분모를 $d$ 라 하면 그것은 「$N$ 이 $d$ 의 배수」와 같은 말이다. 두 계급이 있으면
 * $N$ 은 두 분모의 **공배수**이고, 가장 작은 것은 최소공배수다 — $N$ 을 하나씩 넣어
 * 보는 걸음이 한 번도 없다(D-115 ⑾ 의 «중»).
 *
 * ⚠️ 그 자가 «아니오»를 낼 수 있음은 시험이 **두 분모가 서로소인 판**으로 보인다 —
 *    그때는 최소공배수가 두 수의 곱 그대로라 「곱으로 본 오답」과 **안 갈린다.**
 */
export function smallestTotalCount(p100: number, q100: number): number {
  return lcm(relativeDenominator(p100), relativeDenominator(q100));
}

/** 그때 두 계급의 도수의 합 — 이 유형의 정답. */
export function classFrequencySum(p100: number, q100: number): number {
  const n = smallestTotalCount(p100, q100);
  return (n * (p100 + q100)) / 100;
}

/**
 * 「최소공배수 $=$ 두 수의 곱」으로 잘못 아는 학생의 답.
 *
 * 두 분모가 서로소이면 이 값이 **참 답과 정확히 같아진다** — 개념이 틀린 학생이
 * 맞는다. 생성기가 그런 판을 버리고, 판정기는 이 값을 `withoutBinding` 축으로 쓴다.
 */
export function productTotalAnswer(p100: number, q100: number): number {
  const d1 = relativeDenominator(p100);
  const d2 = relativeDenominator(q100);
  return (d1 * d2 * (p100 + q100)) / 100;
}

/** 상대도수의 지면 글자 — `0.35`·`0.4`(뒤 $0$ 은 안 적는다). */
function rateTex(p100: number): string {
  return String(p100 / 100);
}

/**
 * 🔴 **상대도수 뒤에 붙는 조사는 «지면에 찍힌 글자»로 정해야 한다.**
 *
 * `rateTex(20)` 은 `0.2` 다 — 뒤 $0$ 을 안 적으므로 읽을 때 마지막에 오는 수가
 * $20$(이십, 받침)이 아니라 $2$(이, 모음)로 **바뀐다.** 처음에 `waGwa(p100)` 을
 * 그대로 썼더니 지면에 `$N\times0.2$과` 가 나갔고, 공용 조사 자
 * (`josaMismatches`)가 실제로 그것을 잡아 줬다(실측 씨앗 220×3 에서 2종).
 * 값 검산·냄새 자·KaTeX 는 이 부류를 **구조적으로 못 본다.**
 */
function rateTail(p100: number): number {
  const t = rateTex(p100);
  return Number(t[t.length - 1]);
}

