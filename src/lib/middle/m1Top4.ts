/**
 * 🔴 **여기서도 굳지 않는다.**
 *
 * 겉넓이가 $S=2ab+2h(a+b)$ 이므로 양변을 $2$ 로 나누면 $ab+h(a+b)=K$ 이고,
 * 미지수가 둘인데 식이 하나뿐이다. 중1은 이것을 $(a+h)(b+h)=K+h^{2}$ 로 접는
 * 인수분해를 모르므로, $a=1,2,3,\dots$ 을 차례로 놓고 그때마다
 * $b=(K-ha)\div(a+h)$ 가 자연수인지 **실제로 나눠 봐야** 한다.
 *
 * 끝나는 근거조차 계산이 아니라 **견줌**이다 — $a>b$ 가 되는 순간(즉
 * $a^{2}+2ha>K$) 가로와 세로를 바꾼 것이라 이미 센 것과 같다.
 *
 * ⚠️ 그 자가 «아니오»를 낼 수 있음은 시험이 $h$ 가 크고 $K$ 가 작은 판으로 보인다 —
 *    그때는 살아남는 밑면이 **하나도 없다**(빈 집합).
 */
export function boxDimensionPairs(h: number, k: number): [number, number][] {
  const out: [number, number][] = [];
  for (let a = 1; a * a + 2 * h * a <= k; a += 1) {
    const den = a + h;
    const numer = k - h * a;
    if (numer > 0 && numer % den === 0) out.push([a, numer / den]);
  }
  return out;
}

