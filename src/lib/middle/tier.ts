import type { Difficulty } from "@/contracts/difficulty";

/**
 * **중등 문항의 밑단(`연산`)을 발문에서 가려낸다** (D-106, 2026-08-25).
 *
 * ## 왜 필요한가
 *
 * 초등 엔진은 소단원마다 네 갈래(연산·기본·응용·심화)를 **직접 등록**한다(D-71/72).
 * 중등 엔진은 RPM 유형 873개에 사람이 세 칸(easy·mid·hard)을 손으로 적어 둔 것이
 * 전부라, 축을 하나로 합치면서 그 셋을 위 세 칸(기본·응용·심화)에 얹었다.
 * 그러면 **`연산` 칸이 중등에서 통째로 빈다** — 하위반 프리셋(연산 40%)이 중등
 * 시험지에서는 한 문항도 못 채우고 계속 대체만 한다.
 *
 * ## 무엇을 열쇠로 삼았나 — 낱말이 아니라 **모양**
 *
 * 873유형을 전량 훑어 발문의 «지시»를 빈도순으로 늘어놓고 골랐다
 * (`npx tsx scripts/qa/census-middle-instructions.ts` — 유형이 늘면 다시 돌릴 것).
 * 갈라 주는 것은 두 가지가 **동시에** 참인가다:
 *
 *   ⑴ 한글 문장이 **딱 하나**이고, 그 문장 **안에 수식이 없다**
 *      → 상황도 조건도 없이 「식이 따로 주어지고 지시가 하나」인 모양.
 *   ⑵ 그 지시가 **주어진 식을 바꿔 다시 쓰라**는 것이다
 *      (계산·전개·인수분해·간단히·풀이·유리화·나타내기).
 *
 * ⑵ 가 없으면 「다음 수 중에서 소수의 **개수를 구하시오**」·「다음 자료의 **중앙값**」·
 * 「모두 **고르시오**」가 같이 들어온다. 그것들은 판별·선택이지 계산이 아니다.
 * 실측: 「지시문 하나뿐」 95유형 중 ⑵ 를 만족하는 것 75, 그중 지금 `기본` 인 것 **31**.
 *
 * ## 왜 `기본` 만 내리나 — 연산은 **갈래가 아니라 밑단**이다
 *
 * 같은 「다음 식을 계산하시오」가 `응용`·`심화` 에도 있다(실측 44유형). 그것들은
 * 어려운 계산이다 — 「다음 수의 분모를 유리화하시오」(심화)를 연산으로 내리면
 * 하위반 시험지에 근호 유리화가 들어간다. 사다리에서 **한 칸도 옮기지 않는다.**
 *
 * ## 왜 표가 아니라 규칙인가, 그리고 그 규칙을 무엇이 지키나
 *
 * 31개를 손으로 적어 두면 유형의 발문이 바뀌어도 표는 **조용히 그대로**다
 * (이 저장소가 「손 목록은 세는 쪽과 고치는 쪽을 같이 눈멀게 한다」로 여러 번 데인 자리).
 * 그래서 규칙으로 두되, **그 규칙이 지금 무엇을 잡는지**를
 * `src/__tests__/unit/middleTierYeonsan.test.ts` 가 **키 31개 그대로** 잠근다 —
 * 발문이 바뀌어 집합이 달라지면 조용히 넘어가지 않고 빨개진다.
 */

/** 지시가 「주어진 식을 바꿔 다시 써라」인가. 낱말은 873유형 census 에서 골랐다. */
const OPERATION_INSTRUCTION =
  /(계산하시오|전개하시오|인수분해하시오|간단히 하시오|간단히 나타내시오|푸시오|유리화하시오|나타내시오)\.?$/;

/**
 * 발문이 「지시문 하나뿐」인가 — 맞으면 그 문장을, 아니면 `null`.
 *
 * 수식을 먼저 지운 뒤 **한글이 든 조각**만 센다. 우리 발문은 「지시. ↵ $식$」 꼴이라
 * 마침표로만 자르면 수식 줄이 한 문장으로 세어져 언제나 둘이 된다.
 */
export function loneInstruction(content: string): string | null {
  const plain = content
    .replace(/\$[^$]*\$/g, "◇")
    .replace(/[ \t]+/g, " ")
    .trim();
  const korean = plain
    .split(/(?<=[.?])\s|\n/)
    .map((x) => x.trim())
    .filter((x) => /[가-힣]/.test(x));
  if (korean.length !== 1) return null;
  const only = korean[0]!;
  // 문장 **안**에 수식이 있으면 상황·조건이 있는 것이다 (「◇ 일 때, …」).
  return only.includes("◇") ? null : only;
}

/**
 * 등록된 난이도를 그대로 두거나, 밑단이면 `연산` 으로 내린다.
 *
 * ⚠️ **내리기만 한다.** 올리지 않는다 — 유형에 적힌 값은 사람이 RPM 을 보고 정한
 *    것이고, 발문 모양만 보고 그것을 올릴 근거는 없다.
 */
export function resolveMiddleTier(
  declared: Difficulty,
  content: string,
  hasFigure: boolean,
): Difficulty {
  if (declared !== "기본" || hasFigure) return declared;
  const only = loneInstruction(content);
  if (!only || !OPERATION_INSTRUCTION.test(only)) return declared;
  return "연산";
}
