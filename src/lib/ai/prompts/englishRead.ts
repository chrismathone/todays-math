export function buildEnglishReadPrompt(): string {
  return [
    INTRO,
    "규칙:",
    ...RULES.map((rule, index) => `${index + 1}. ${rule}`),
  ].join("\n");
}

/**
 * 한 번 더 대조 — 읽은 글을 같은 사진과 다시 맞춰 보게 하는 둘째 호출의 지시문(대조 v1 · 2026-10-06).
 * Gemini 3.8 Flash 에서 이 호출을 붙이자 흠 없이 옮긴 쪽이 73% → 88%, 큰 흠이 19 → 8 곳이 됐다(33번 읽기 · 25 §13.9).
 * Claude 쪽은 좋아졌다 나빠졌다 해 차이를 말할 수 없었다 — 그래서 기본은 Gemini 일 때만 켬이다(`readPhoto.ts`).
 * 고친 **전체 글**을 다시 받는다 — 고칠 곳 목록을 받아 꿰매지 않는다.
 */
const VERIFY: readonly string[] = [
  "아래 [옮긴 글]은 이 사진을 [지시문]대로 옮겨 적은 것입니다. 사진과 처음부터 끝까지 한 줄씩 다시 대조하고, 지시문에 어긋난 곳만 고쳐 전체 글을 다시 출력합니다.",
  "- 빠뜨린 인쇄 글자(낱말표의 뜻 · 빈칸 앞의 첫 글자 · 문항 · 보기 · 머리줄)를 채웁니다.",
  "- 섞여 든 손글씨(빈칸에 쓴 답 · 필기 · 손으로 쓴 반 · 번호 · 이름)를 뺍니다.",
  "- 잘못 읽은 글자(한글 받침 · 닮은 글자 · 숫자)를 사진대로 고칩니다.",
  "- 사진에 없는 기호 · 낱말을 뺍니다.",
  "맞게 옮긴 곳은 한 글자도 바꾸지 않습니다. 고칠 곳이 없으면 그대로 출력합니다. 설명 없이 고친 글만 출력합니다.",
];

export function buildEnglishReadVerifyPrompt(text: string): string {
  return [
    VERIFY.join("\n"),
    "",
    "[지시문]",
    buildEnglishReadPrompt(),
    "",
    "[옮긴 글]",
    text.trim(),
  ].join("\n");
}
