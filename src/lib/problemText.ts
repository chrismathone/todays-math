/**
 * 발문 다듬기 — **두 엔진이 같이 쓰는 한 곳**.
 *
 * 규칙을 초등·중등에 따로 두면 한쪽만 고쳐도 아무도 모른다. 이 저장소가 되풀이한
 * 자리라(「같은 규칙을 쓰는 자리가 둘이면 한 숫자를 두 곳이 쓰게 하라」) 여기 모은다.
 */

/**
 * 「단, …」 조건절을 **괄호 안에** 넣는다 (원장님 지시 2026-08-25:
 * *「"단, ~~" 이 들어가는 부분은 전부 괄호 안에 넣을 수 있도록」*).
 *
 * 교과서 표기가 그렇다 — 조건절은 발문 본체와 괄호로 갈린다:
 *
 *   전: `… 둘레는 몇 cm인가? 단, 정육각형의 여섯 꼭짓점은 모두 원 위에 있습니다.`
 *   후: `… 둘레는 몇 cm인가? (단, 정육각형의 여섯 꼭짓점은 모두 원 위에 있습니다.)`
 *
 * 뒤에 딸린 「또, …」 까지 **한 괄호 안**에 넣는다 — 조건이 둘이어도 조건은 조건이다.
 *
 * ## 손대지 않는 경우 — 넓히면 틀린다
 *
 * ⚠️ 이 함수는 **글의 끝에 붙은 조건절**만 다룬다. 다음은 그대로 둔다:
 *   · 이미 괄호가 쳐진 것 — 두 겹이 된다.
 *   · 뒤에 **보기(①②③④⑤)** 가 오는 것 — 「단,」이 발문 중간이라 괄호가 보기를 삼킨다.
 *   · 뒤에 **줄바꿈**이 있는 것 — 다음 줄은 조건이 아니라 다른 덩어리(수식·표)다.
 *   · 뒤에 **괄호가 이미 섞인** 것 — `(단, $a$ 는 자연수)` 처럼 안쪽에 괄호가 있으면
 *     바깥을 한 겹 더 씌울 때 짝이 헷갈린다.
 *
 * 실측(2026-08-25): 초등 920갈래 중 **7건**, 중등 873유형 중 **0건**(중등은 이미 33건
 * 전부 괄호를 치고 있었다).
 */
export function wrapDanClause(content: string): string {
  // 이미 괄호 안이면 손대지 않는다.
  if (/\(\s*단,/.test(content)) return content;

  // 문장 첫머리의 「단,」 — 글 처음이거나, 문장부호 뒤이거나, 줄 처음.
  const m = /(^|[.?!]\s|\n)단,/.exec(content);
  if (!m) return content;

  const at = m.index + m[1].length;
  const rest = content.slice(at);

  // 조건절 뒤에 보기·줄바꿈·괄호가 있으면 «끝에 붙은 조건»이 아니다.
  if (/[①②③④⑤\n()]/.test(rest)) return content;

  const trimmed = rest.replace(/\s+$/, "");
  const trailingWs = rest.slice(trimmed.length);
  return `${content.slice(0, at)}(${trimmed})${trailingWs}`;
}
