import type {
  ApplyItem,
  ConceptBlankBank,
  ConceptEntry,
  FigureItem,
  OxItem,
} from "@/contracts/conceptBlank.contract";

/**
 * 개념 백지 은행 — 중2. 트랙 cb-m2 (D-150 · 26번 문서 §5).
 * 교재는 «어떤 용어가 어느 소단원에 있나»만 참고했고, 문장 · 수 · 그림은 모두 새로 썼다.
 * 수식은 `$...$`(KaTeX). 뜻 문장의 `{ }` 는 핵심어 자리다 — 그 안에 수식을 넣지 않는다.
 */
export const bank: ConceptBlankBank = {
  concepts: [],
  ox: [],
  apply: [],
  figures: [],
};

type Level = ConceptEntry["level"];
type C = [
  term: string,
  kind: ConceptEntry["kind"],
  level: Level,
  definition: string,
  example?: [prompt: string, answer: string],
];
type O = [level: OxItem["level"], statement: string, answer: boolean, why: string];
type A = [level: ApplyItem["level"], prompt: string, answer: string];
type F = [
  level: FigureItem["level"],
  prompt: string,
  svg: string,
  tags: FigureItem["tags"],
  lines: FigureItem["lines"],
];

const CHAPTERS: Record<string, string> = {
  "01": "1. 수와 식",
  "02": "2. 부등식",
  "03": "3. 방정식",
  "04": "4. 함수",
  "05": "5. 도형의 성질",
  "06": "6. 도형의 닮음",
  "07": "7. 닮음의 활용",
  "08": "8. 피타고라스 정리",
  "09": "9. 확률",
};

/**
 * 소단원 하나를 은행에 싣는다. `code` 는 «대단원 두 자리-그 안 차례 두 자리»이고 id 의 몸이 된다
 * (`m2-01-03-c1` — c 개념 · o ○× · a 적용 · f 그림). 차례는 아래에 적힌 순서 그대로다(고정).
 */
function section(
  code: string,
  title: string,
  body: { c: C[]; o: O[]; a: A[]; f?: F[] },
) {
  const key = `중2::${CHAPTERS[code.slice(0, 2)]}::${title}`;
  body.c.forEach(([term, kind, level, definition, example], i) => {
    bank.concepts.push({
      id: `m2-${code}-c${i + 1}`,
      section: key,
      term,
      kind,
      level,
      definition,
      ...(example
        ? { example: { prompt: example[0], answer: example[1] } }
        : {}),
    });
  });
  body.o.forEach(([level, statement, answer, why], i) => {
    bank.ox.push({
      id: `m2-${code}-o${i + 1}`,
      section: key,
      level,
      statement,
      answer,
      why,
    });
  });
  body.a.forEach(([level, prompt, answer], i) => {
    bank.apply.push({
      id: `m2-${code}-a${i + 1}`,
      section: key,
      level,
      prompt,
      answer,
    });
  });
  (body.f ?? []).forEach(([level, prompt, svg, tags, lines], i) => {
    bank.figures.push({
      id: `m2-${code}-f${i + 1}`,
      section: key,
      level,
      prompt,
      viewBox: "0 0 200 125",
      svg,
      tags,
      lines,
    });
  });
}

/** TeX 의 역슬래시를 그대로 쓰려는 꼬리표(`r\`$\frac12$\``). */
const r = String.raw;

/* ───────── 그림 연장 — 지면 팔레트(선 #1F1F23 · 보조 #6B6B72 · 금 #A57F00 · 칠 #F7F3E6) ───────── */

const INK =
  'stroke="#1F1F23" stroke-width="1.5" fill="none" stroke-linejoin="round" stroke-linecap="round"';
const SUB = 'stroke="#6B6B72" stroke-width="1" fill="none"';
const DASH = `${SUB} stroke-dasharray="4 3"`;
const FILL =
  'fill="#F7F3E6" stroke="#1F1F23" stroke-width="1.5" stroke-linejoin="round"';
const GOLD =
  'stroke="#A57F00" stroke-width="1.8" fill="none" stroke-linecap="round"';
const poly = (points: string, style = FILL) =>
  `<polygon points="${points}" ${style}/>`;
const path = (d: string, style = INK) => `<path d="${d}" ${style}/>`;
const dot = (x: number, y: number, fill = "#1F1F23") =>
  `<circle cx="${x}" cy="${y}" r="2.2" fill="${fill}"/>`;
const ring = (x: number, y: number, radius: number, style = INK) =>
  `<circle cx="${x}" cy="${y}" r="${radius}" ${style}/>`;
/** 점 · 직선의 이름(기울인 로마자). */
const name = (x: number, y: number, value: string) =>
  `<text x="${x}" y="${y}" text-anchor="middle" font-family="serif" font-style="italic" font-size="11" fill="#1F1F23">${value}</text>`;
/** 수 · 길이 · 짧은 글(곧은 글씨). */
const note = (x: number, y: number, value: string) =>
  `<text x="${x}" y="${y}" text-anchor="middle" font-family="sans-serif" font-size="10" fill="#1F1F23">${value}</text>`;
/** 좌표축 — 원점 (ox, oy), 화살표와 x · y · O 글자까지. 직선이 원점 왼쪽 아래를 지나면 O 를 오른쪽에 둔다. */
const axes = (ox: number, oy: number, originRight = false) =>
  path(
    `M10 ${oy}H188 M184 ${oy - 3}L188 ${oy}L184 ${oy + 3} M${ox} 120V6 M${ox - 3} 10L${ox} 6L${ox + 3} 10`,
    SUB,
  ) +
  name(194, oy + 4, "x") +
  name(ox + 8, 12, "y") +
  name(originRight ? ox + 8 : ox - 7, oy + 11, "O");

const MARK = 'stroke="#A57F00" stroke-width="1.2" fill="none"';
const TICK = 'stroke="#1F1F23" stroke-width="1.1" fill="none"';
const q = (n: number) => Math.round(n * 10) / 10;
const unit = (x1: number, y1: number, x2: number, y2: number) => {
  const d = Math.hypot(x2 - x1, y2 - y1);
  return [(x2 - x1) / d, (y2 - y1) / d] as const;
};
/** 같은 길이 표시 — 선분 한가운데에 짧은 빗금 count 개. */
function tick(x1: number, y1: number, x2: number, y2: number, count = 1) {
  const [ux, uy] = unit(x1, y1, x2, y2);
  const mx = (x1 + x2) / 2;
  const my = (y1 + y2) / 2;
  let d = "";
  for (let i = 0; i < count; i++) {
    const o = (i - (count - 1) / 2) * 3;
    const cx = mx + ux * o;
    const cy = my + uy * o;
    d += `M${q(cx + uy * 3.5)} ${q(cy - ux * 3.5)}L${q(cx - uy * 3.5)} ${q(cy + ux * 3.5)}`;
  }
  return path(d, TICK);
}
/** 직각 표시 — 꼭짓점 (x, y)에서 두 변 위의 점 (ax, ay) · (bx, by) 쪽으로 난 작은 네모. */
function rightAngle(
  x: number,
  y: number,
  ax: number,
  ay: number,
  bx: number,
  by: number,
  size = 6,
) {
  const [ux, uy] = unit(x, y, ax, ay);
  const [vx, vy] = unit(x, y, bx, by);
  return path(
    `M${q(x + ux * size)} ${q(y + uy * size)}L${q(x + (ux + vx) * size)} ${q(y + (uy + vy) * size)}L${q(x + vx * size)} ${q(y + vy * size)}`,
    SUB,
  );
}
/** 각 표시 — 꼭짓점 (x, y)에서 두 변 위의 점 사이에 그리는 호(금색). */
function arc(
  x: number,
  y: number,
  ax: number,
  ay: number,
  bx: number,
  by: number,
  radius = 11,
) {
  const [ux, uy] = unit(x, y, ax, ay);
  const [vx, vy] = unit(x, y, bx, by);
  const sweep = ux * vy - uy * vx > 0 ? 1 : 0;
  return path(
    `M${q(x + ux * radius)} ${q(y + uy * radius)}A${radius} ${radius} 0 0 ${sweep} ${q(x + vx * radius)} ${q(y + vy * radius)}`,
    MARK,
  );
}

