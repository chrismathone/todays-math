/**
 * 개념 백지 은행 — 중3(D-150 · 26번 문서 §5). 교재는 «어떤 용어가 어느 소단원에 있나»만 참고했고 문장 · 수치 · 그림은 새로 썼다.
 *
 * 표기는 제품과 같은 KaTeX(2차 · 원장님 2026-09-30) — 모든 수는 `$...$`, 단위는 수식 안(`$4\,\mathrm{cm}$`), 점 이름은
 * `\mathrm` 없이(`$\overline{AB}$` · `$\angle A$` — 제품 수식 경로가 곧게 세운다). 핵심어가 수 · 식이면 `{$...$}`
 * (수식 안의 `{ }` 는 TeX 묶음이라 핵심어가 아니다). 그림 이름표(`tags`)와 SVG 안 글자만 글자 그대로다.
 *
 * 🔴 고정 문항 — id 는 목록의 자리에서 나온다. 문항을 뺄 때는 줄을 지우지 말고 `null` 로 자리를 남긴다(뒤 번호가 밀리지 않게).
 */
export const bank: ConceptBlankBank = {
  concepts: [],
  ox: [],
  apply: [],
  figures: [],
};

const r = String.raw;

type Level = ConceptEntry["level"];
type Concept = [
  term: string,
  kind: ConceptEntry["kind"],
  level: Level,
  definition: string,
  example?: [prompt: string, answer: string],
];
type Ox = [level: Level, statement: string, answer: boolean, why: string];
type Apply = [level: Level, prompt: string, answer: string];
type Figure = {
  level: Level;
  prompt: string;
  svg: string;
  tags?: FigureItem["tags"];
  lines: FigureItem["lines"];
};

/** 차례와 번호는 아래 고정 목록의 순서로만 정한다 — 무작위 · 바깥 자료 없음. */
function section(
  code: string,
  chapter: string,
  title: string,
  body: {
    /** `null` = 뺀 문항의 빈 자리(번호만 센다). */
    concepts: (Concept | null)[];
    ox: Ox[];
    apply: Apply[];
    figures?: Figure[];
  },
) {
  const key = `중3::${chapter}::${title}`;
  const id = (kind: string, i: number) => `m3-${code}-${kind}${i + 1}`;
  body.concepts.forEach((concept, i) => {
    if (!concept) return;
    const [term, kind, level, definition, example] = concept;
    const entry: ConceptEntry = {
      id: id("c", i),
      section: key,
      term,
      kind,
      level,
      definition,
    };
    if (example) entry.example = { prompt: example[0], answer: example[1] };
    bank.concepts.push(entry);
  });
  body.ox.forEach(([level, statement, answer, why], i) => {
    const item: OxItem = {
      id: id("o", i),
      section: key,
      level,
      statement,
      answer,
      why,
    };
    bank.ox.push(item);
  });
  body.apply.forEach(([level, prompt, answer], i) => {
    const item: ApplyItem = {
      id: id("a", i),
      section: key,
      level,
      prompt,
      answer,
    };
    bank.apply.push(item);
  });
  (body.figures ?? []).forEach((figure, i) => {
    bank.figures.push({
      id: id("f", i),
      section: key,
      level: figure.level,
      prompt: figure.prompt,
      viewBox: "0 0 200 125",
      svg: figure.svg,
      tags: figure.tags ?? [],
      lines: figure.lines,
    });
  });
}

/* ───────── 그림 도구 — 좌표는 viewBox 0 0 200 125, 색은 지면 팔레트 ───────── */

const INK = "#1F1F23";
const SUB = "#6B6B72";
const GOLD = "#A57F00";
const FILL = "#F7F3E6";

type Pt = readonly [number, number];

const n = (v: number) => String(Math.round(v * 100) / 100);
const at = (p: Pt) => `${n(p[0])} ${n(p[1])}`;
/** 원 위의 점 — 각도는 수학 방향(반시계), 화면 y 는 아래로 자란다. */
const on = (c: Pt, radius: number, deg: number): Pt => [
  c[0] + radius * Math.cos((deg * Math.PI) / 180),
  c[1] - radius * Math.sin((deg * Math.PI) / 180),
];
const unit = (a: Pt, b: Pt): Pt => {
  const d = Math.hypot(b[0] - a[0], b[1] - a[1]);
  return [(b[0] - a[0]) / d, (b[1] - a[1]) / d];
};
/** a 에서 b 쪽으로 len 만큼 간 점. */
const toward = (a: Pt, b: Pt, len: number): Pt => {
  const u = unit(a, b);
  return [a[0] + u[0] * len, a[1] + u[1] * len];
};
const mid = (a: Pt, b: Pt): Pt => [(a[0] + b[0]) / 2, (a[1] + b[1]) / 2];

const seg = (a: Pt, b: Pt, stroke = INK, width = 1.6, dash = "") =>
  `<line x1="${n(a[0])}" y1="${n(a[1])}" x2="${n(b[0])}" y2="${n(b[1])}" stroke="${stroke}" stroke-width="${width}"${
    dash ? ` stroke-dasharray="${dash}"` : ""
  }/>`;
const curve = (d: string, stroke = INK, width = 1.6, dash = "") =>
  `<path d="${d}" fill="none" stroke="${stroke}" stroke-width="${width}"${
    dash ? ` stroke-dasharray="${dash}"` : ""
  }/>`;
const ring = (c: Pt, radius: number, fill = FILL) =>
  `<circle cx="${n(c[0])}" cy="${n(c[1])}" r="${n(radius)}" fill="${fill}" stroke="${INK}" stroke-width="1.6"/>`;
const dot = (p: Pt, fill = INK, radius = 2.2) =>
  `<circle cx="${n(p[0])}" cy="${n(p[1])}" r="${radius}" fill="${fill}"/>`;
const poly = (points: Pt[], fill = FILL) =>
  `<polygon points="${points.map((p) => `${n(p[0])},${n(p[1])}`).join(" ")}" fill="${fill}" stroke="${INK}" stroke-width="1.6" stroke-linejoin="round"/>`;
const box = (x: number, y: number, w: number, h: number, fill = "none") =>
  `<rect x="${x}" y="${y}" width="${w}" height="${h}" fill="${fill}" stroke="${INK}" stroke-width="1.6"/>`;
const word = (x: number, y: number, value: string, fill = INK, size = 11) =>
  `<text x="${n(x)}" y="${n(y)}" text-anchor="middle" font-family="sans-serif" font-size="${size}" fill="${fill}">${value}</text>`;
/** 이름표로 가는 가는 안내선. */
const leader = (a: Pt, b: Pt) => seg(a, b, SUB, 0.9);

/** 직각 표시 — 꼭짓점 v 에서 a · b 쪽으로 난 두 변 사이. */
const square = (v: Pt, a: Pt, b: Pt, size = 7) => {
  const p = toward(v, a, size);
  const q = toward(v, b, size);
  const corner: Pt = [p[0] + q[0] - v[0], p[1] + q[1] - v[1]];
  return curve(`M${at(p)}L${at(corner)}L${at(q)}`, INK, 1);
};
/** 각 표시(작은 호) — 꼭짓점 v 에서 a 쪽 변부터 b 쪽 변까지. */
const angle = (v: Pt, a: Pt, b: Pt, radius = 14, stroke = GOLD) => {
  const ua = unit(v, a);
  const ub = unit(v, b);
  const sweep = ua[0] * ub[1] - ua[1] * ub[0] > 0 ? 1 : 0;
  return curve(
    `M${at(toward(v, a, radius))}A${radius} ${radius} 0 0 ${sweep} ${at(toward(v, b, radius))}`,
    stroke,
    1.4,
  );
};
/** 같은 길이 표시 — 선분 한가운데의 짧은 금색 눈금. */
const tick = (a: Pt, b: Pt) => {
  const m = mid(a, b);
  const u = unit(a, b);
  return seg(
    [m[0] - u[1] * 3.5, m[1] + u[0] * 3.5],
    [m[0] + u[1] * 3.5, m[1] - u[0] * 3.5],
    GOLD,
    1.4,
  );
};
/** 좌표축 — 원점 o, x축은 left~right, y축은 top~bottom. 원점 글자 자리는 oAt. */
const axes = (
  o: Pt,
  left: number,
  right: number,
  top: number,
  bottom: number,
  oAt: Pt = [o[0] - 7, o[1] + 11],
) =>
  seg([left, o[1]], [right, o[1]], INK, 1.1) +
  seg([o[0], bottom], [o[0], top], INK, 1.1) +
  curve(
    `M${right - 5} ${o[1] - 3}L${right} ${o[1]}L${right - 5} ${o[1] + 3}`,
    INK,
    1.1,
  ) +
  curve(
    `M${o[0] - 3} ${top + 5}L${o[0]} ${top}L${o[0] + 3} ${top + 5}`,
    INK,
    1.1,
  ) +
  word(right - 2, o[1] + 12, "x", INK, 10) +
  word(o[0] + 8, top + 7, "y", INK, 10) +
  word(oAt[0], oAt[1], "O", INK, 10);
/** 포물선 — 꼭짓점 v, 양 끝은 v 에서 좌우 half 만큼 떨어진 높이 endY. 2차 베지어는 포물선을 그대로 그린다. */
const parabola = (v: Pt, half: number, endY: number) =>
  curve(
    `M${n(v[0] - half)} ${n(endY)}Q${n(v[0])} ${n(2 * v[1] - endY)} ${n(v[0] + half)} ${n(endY)}`,
  );
/** 상자그림 — 다섯 값의 x 자리와 상자의 위쪽 y · 높이. */
const boxplot = (
  top: number,
  height: number,
  [min, q1, median, q3, max]: readonly [number, number, number, number, number],
) => {
  const center = top + height / 2;
  return (
    seg([min, center], [q1, center], INK, 1.4) +
    seg([q3, center], [max, center], INK, 1.4) +
    seg([min, center - 5], [min, center + 5], INK, 1.4) +
    seg([max, center - 5], [max, center + 5], INK, 1.4) +
    box(q1, top, q3 - q1, height, FILL) +
    seg([median, top], [median, top + height])
  );
};
/** 산점도의 점들. */
const scatter = (points: Pt[]) => points.map((p) => dot(p, INK, 2.3)).join("");

