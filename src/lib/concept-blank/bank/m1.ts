/**
 * 개념 백지 은행 — 중1(D-150 · 26번 문서 §5). 교재는 «어떤 용어가 어느 소단원에 있나»만 참고하고
 * 문장 · 예 · 수치 · 그림은 모두 새로 썼다.
 *
 * 표기는 제품과 같은 KaTeX 다(cb-pass2 · 원장님 2026-09-30 «카텍스 사용할 것»): 숫자 · 식 · 기호는 모두 `$...$`,
 * 단위는 수식 안(`$7\,\mathrm{cm}$` · `$20\%$` · `$50^\circ$`), 점 이름은 `\mathrm` 없이(`$\overline{AB}$` · `$\angle A$` · 점 `$A$`),
 * 핵심어가 수 · 식이면 `{$...$}`. 그림 이름표(`tags`)와 SVG 안 글자만 글자 그대로다(SVG 는 KaTeX 를 못 쓴다).
 * 기준 교육과정은 2022 개정(교육부 고시 제2022-33호) — 그 밖이라 뺀 문항은 자리에 `RETIRED` 를 둔다.
 */
export const bank: ConceptBlankBank = {
  concepts: [],
  ox: [],
  apply: [],
  figures: [],
};

/** 수식이 든 글은 `r` 로 쓴다 — 역슬래시를 그대로 둔다. */
const r = String.raw;

type Concept = [
  term: string,
  kind: ConceptEntry["kind"],
  level: ConceptEntry["level"],
  definition: string,
  example?: [prompt: string, answer: string],
];
type Ox = [
  level: OxItem["level"],
  statement: string,
  answer: boolean,
  why: string,
];
type Apply = [level: ApplyItem["level"], prompt: string, answer: string];

const chapters: Record<string, string> = {
  "01": "1. 소인수분해",
  "02": "2. 정수와 유리수",
  "03": "3. 방정식",
  "04": "4. 그래프와 비례",
  "05": "5. 기본 도형",
  "06": "6. 평면도형",
  "07": "7. 입체도형",
  "08": "8. 통계",
};
const sectionKeys: Record<string, string> = {};

/** 뺀 문항의 자리 — 고정 문항이라 뒤 문항의 번호(id)가 밀리면 안 된다. 지우지 말고 이것으로 바꿔 자리를 남긴다. */
const RETIRED = null;

/** 차례와 번호는 아래 목록의 순서로만 정한다. 새 문항은 그 소단원 배열의 끝에 붙인다(id 가 밀리지 않게). */
function section(
  code: string,
  title: string,
  concepts: (Concept | typeof RETIRED)[],
  ox: (Ox | typeof RETIRED)[],
  apply: (Apply | typeof RETIRED)[],
) {
  const key = `중1::${chapters[code.slice(0, 2)]}::${title}`;
  sectionKeys[code] = key;
  concepts.forEach((entry, i) => {
    if (entry === RETIRED) return;
    const [term, kind, level, definition, example] = entry;
    bank.concepts.push({
      id: `m1-${code}-c${i + 1}`,
      section: key,
      term,
      kind,
      level,
      definition,
      ...(example
        ? { example: { prompt: example[0], answer: example[1] } }
        : {}),
    });
  });
  ox.forEach((entry, i) => {
    if (entry === RETIRED) return;
    const [level, statement, answer, why] = entry;
    bank.ox.push({
      id: `m1-${code}-o${i + 1}`,
      section: key,
      level,
      statement,
      answer,
      why,
    });
  });
  apply.forEach((entry, i) => {
    if (entry === RETIRED) return;
    const [level, prompt, answer] = entry;
    bank.apply.push({
      id: `m1-${code}-a${i + 1}`,
      section: key,
      level,
      prompt,
      answer,
    });
  });
}

