function plane(
  opt: {
    ticks?: boolean;
    names?: boolean;
    ones?: boolean;
    origin?: [number, number];
  } = {},
) {
  const { ticks = true, names = true, ones = false, origin = [93, 76] } = opt;
  let s = `<path d="M14 64H188 M184 61L188 64L184 67 M100 120V6 M97 10L100 6L103 10" ${GUIDE}/>`;
  if (ticks) {
    const xs = [-7, -6, -5, -4, -3, -2, -1, 1, 2, 3, 4, 5, 6, 7];
    const ys = [-4, -3, -2, -1, 1, 2, 3, 4];
    s += `<path d="${xs.map((x) => `M${px(x)} 62V66`).join(" ")} ${ys.map((y) => `M98 ${py(y)}H102`).join(" ")}" ${GUIDE}/>`;
  }
  if (names)
    s +=
      italic(193, 76, "x") +
      italic(108, 12, "y") +
      label(origin[0], origin[1], "O");
  if (ones) s += label(112, 78, "1") + label(92, 56, "1");
  return s;
}
/** 함수의 그래프를 촘촘한 꺾은선으로 — 값은 고정이고 무작위가 없다. */
function curve(f: (x: number) => number, from: number, to: number) {
  const points: string[] = [];
  for (let i = 0; from + i * 0.25 <= to + 1e-9; i++) {
    const x = from + i * 0.25;
    points.push(`${px(x)},${py(f(x))}`);
  }
  return `<polyline points="${points.join(" ")}" ${INK}/>`;
}

