/** 함수의 그래프를 촘촘한 꺾은선으로 — 값은 고정이고 무작위가 없다. */
function curve(f: (x: number) => number, from: number, to: number) {
  const points: string[] = [];
  for (let i = 0; from + i * 0.25 <= to + 1e-9; i++) {
    const x = from + i * 0.25;
    points.push(`${px(x)},${py(f(x))}`);
  }
  return `<polyline points="${points.join(" ")}" ${INK}/>`;
}

