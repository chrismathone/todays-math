    const ys = [-4, -3, -2, -1, 1, 2, 3, 4];
    s += `<path d="${xs.map((x) => `M${px(x)} 62V66`).join(" ")} ${ys.map((y) => `M98 ${py(y)}H102`).join(" ")}" ${GUIDE}/>`;
