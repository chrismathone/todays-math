/** 수식이 든 글을 새로 쓸 때는 `r` 로 쓴다 — 역슬래시를 그대로 둔다(전수 검토 2026-10-02). */
const r = String.raw;

/** 초4 고정 은행. 용어와 차례만 참고하고, 설명·물음·그림은 새로 작성했다(D-150). */
export const bank: ConceptBlankBank = {
  concepts: [],
  ox: [],
  apply: [],
  figures: [],
};

type ConceptRow = [
  term: string,
  kind: ConceptEntry["kind"],
  level: ConceptEntry["level"],
  definition: string,
];

// 아래에 적힌 순서와 값만 펼친다. 무작위 선택이나 외부 자료 읽기는 없다.
// 번호는 적힌 차례(c1, c2 … · a1)다. 문항을 빼고 새로 넣은 소단원만 `numbers` 로 번호를 적는다 —
// 고정 문항이라 뺀 번호는 다시 쓰지 않고, 새 문항은 그 소단원의 뒤 번호를 받는다.
function section(
  chapter: string,
  title: string,
  concepts: ConceptRow[],
  ox: [statement: string, answer: boolean, why: string],
  apply: [prompt: string, answer: string],
  numbers: { concepts?: number[]; apply?: number } = {},
) {
  const key = `초4::${chapter}::${title}`;
  const prefix = `e4-${title.split(" ")[0]}`;
  concepts.forEach(([term, kind, level, definition], index) => {
    bank.concepts.push({
      id: `${prefix}-c${numbers.concepts?.[index] ?? index + 1}`,
      section: key,
      term,
      kind,
      level,
      definition,
    });
  });
  bank.ox.push({
    id: `${prefix}-o1`,
    section: key,
    level: "중",
    statement: ox[0],
    answer: ox[1],
    why: ox[2],
  });
  bank.apply.push({
    id: `${prefix}-a${numbers.apply ?? 1}`,
    section: key,
    level: "상",
    prompt: apply[0],
    answer: apply[1],
  });
}

