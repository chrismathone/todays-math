  `<line x1="${x1}" y1="${y1}" x2="${x2}" y2="${y2}" stroke="${dashed ? muted : ink}" stroke-width="1.5"${dashed ? ' stroke-dasharray="4 3"' : ""}/>`;
const text = (x: number, y: number, value: string, size = 11) =>
  `<text x="${x}" y="${y}" fill="${ink}" font-family="sans-serif" font-size="${size}" text-anchor="middle">${value}</text>`;
const polygon = (points: string) =>
  `<polygon points="${points}" fill="${paper}" stroke="${ink}" stroke-width="1.5" stroke-linejoin="round"/>`;
const dot = (x: number, y: number) =>
  `<circle cx="${x}" cy="${y}" r="3" fill="${gold}"/>`;
const right = (x: number, y: number, dx = 1, dy = -1) =>
  `<path d="M${x + dx * 9} ${y}v${dy * 9}h${-dx * 9}" fill="none" stroke="${ink}" stroke-width="1"/>`;
const arrow = (x1: number, y1: number, x2: number, y2: number) => {
  const angle = Math.atan2(y2 - y1, x2 - x1);
  const a = [x2 - 6 * Math.cos(angle - 0.45), y2 - 6 * Math.sin(angle - 0.45)];
  const b = [x2 - 6 * Math.cos(angle + 0.45), y2 - 6 * Math.sin(angle + 0.45)];
  return (
    line(x1, y1, x2, y2) +
    `<path d="M${a[0]} ${a[1]}L${x2} ${y2}L${b[0]} ${b[1]}" fill="none" stroke="${ink}" stroke-width="1.5"/>`
  );
};
const ray = (x: number, y: number, length: number, degrees: number) =>
  line(
    x,
    y,
    x + length * Math.cos((degrees * Math.PI) / 180),
    y - length * Math.sin((degrees * Math.PI) / 180),
  );

function figure(
  code: string,
  level: FigureItem["level"],
  prompt: string,
  svg: string,
  lines: FigureItem["lines"],
  tags: FigureItem["tags"] = [],
) {
  const section = bank.concepts.find((c) => c.id === `e4-${code}-c1`)!.section;
  bank.figures.push({
    id: `e4-${code}-f1`,
    section,
    level,
    prompt,
    viewBox: "0 0 200 125",
    svg,
    tags,
    lines,
  });
}

