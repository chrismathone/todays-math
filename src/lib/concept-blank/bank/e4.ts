function lineGraph(
  values: number[],
  labels: string[],
  start: number,
  step: number,
  unit: string,
  broken = false,
) {
  let svg = text(22, 12, unit, 9);
  for (let i = 0; i <= 3; i++) {
    const y = 90 - 20 * i;
    svg +=
      `<g opacity="0.35">${line(40, y, 180, y, true)}</g>` +
      text(25, y + 3, String(start + i * step), 9);
  }
  const baseline = broken ? 102 : 90;
  svg += line(40, 20, 40, baseline) + line(40, baseline, 182, baseline);
  if (broken) {
    svg += `<rect x="35" y="94" width="10" height="5" fill="white"/><path d="M35 97l3 -2l4 3l3 -2" fill="none" stroke="${ink}"/>`;
  }
  const points = values.map((v, i) => [
    56 + i * 50,
    90 - ((v - start) / step) * 20,
  ]);
  svg += `<polyline points="${points.map((p) => p.join(",")).join(" ")}" fill="none" stroke="${ink}" stroke-width="1.5"/>`;
  points.forEach(([x, y], i) => {
    svg += dot(x!, y!) + text(x!, 119, labels[i]!, 9);
  });
  return svg;
}

