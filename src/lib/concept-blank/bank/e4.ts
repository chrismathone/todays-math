function bars(values: number[], labels: string[], step: number, unit: string) {
  let svg = text(24, 12, unit, 9);
  for (let i = 0; i <= 4; i++) {
    const y = 100 - 20 * i;
    svg +=
      `<g opacity="0.35">${line(36, y, 182, y, true)}</g>` +
      text(24, y + 3, String(i * step), 9);
  }
  svg += line(36, 18, 36, 100) + line(36, 100, 184, 100);
  values.forEach((v, i) => {
    const x = 52 + 44 * i;
    svg +=
      `<rect x="${x}" y="${100 - (20 * v) / step}" width="24" height="${(20 * v) / step}" fill="${paper}" stroke="${ink}"/>` +
      text(x + 12, 117, labels[i]!, 10);
  });
  return svg;
}

