/** 초5 고정 은행. 교재는 용어·차례만 참고하고 설명과 수치는 새로 썼다. */
export const bank: ConceptBlankBank = {
  concepts: [],
  ox: [],
  apply: [],
  figures: [],
};

type Concept = [
  term: string,
  kind: ConceptEntry["kind"],
  level: ConceptEntry["level"],
  definition: string,
];
type Ox = [
  level: OxItem["level"],
  statement: string,
  answer: boolean,
  why: string,
];
type Apply = [level: ApplyItem["level"], prompt: string, answer: string];
const chapters: Record<string, string> = {
  "1-1": "자연수의 혼합 계산",
  "1-2": "약수와 배수",
  "1-3": "대응 관계",
  "1-4": "약분과 통분",
  "1-5": "분수의 덧셈과 뺄셈",
  "1-6": "다각형의 둘레와 넓이",
  "2-1": "수의 범위와 어림하기",
  "2-2": "분수의 곱셈",
  "2-3": "합동과 대칭",
  "2-4": "소수의 곱셈",
  "2-5": "직육면체",
  "2-6": "평균과 가능성",
};
const sectionKeys: Record<string, string> = {};

/**
 * 차례와 번호는 아래의 고정 목록에서만 정한다. 외부 자료나 무작위 값은 쓰지 않는다.
 * 고정 문항이라 id 를 다시 쓰지 않는다 — 뺀 문항의 자리는 `null` 로 남겨 번호를 비우고, 새 문항은 뒤 번호에 붙인다.
 */
function section(
  code: string,
  title: string,
  concepts: (Concept | null)[],
  ox: Ox,
  apply: Apply | (Apply | null)[],
) {
  const chapter = code.slice(0, 3);
  const key = `초5::${chapter} ${chapters[chapter]}::${code} ${title}`;
  sectionKeys[code] = key;
  concepts.forEach((concept, i) => {
    if (!concept) return;
    const [term, kind, level, definition] = concept;
    bank.concepts.push({
      id: `e5-${code}-c${i + 1}`,
      section: key,
      term,
      kind,
      level,
      definition,
    });
  });
  const [level, statement, answer, why] = ox;
  bank.ox.push({
    id: `e5-${code}-o1`,
    section: key,
    level,
    statement,
    answer,
    why,
  });
  const applies: (Apply | null)[] =
    typeof apply[0] === "string"
      ? [apply as Apply]
      : (apply as (Apply | null)[]);
  applies.forEach((item, i) => {
    if (!item) return;
    bank.apply.push({
      id: `e5-${code}-a${i + 1}`,
      section: key,
      level: item[0],
      prompt: item[1],
      answer: item[2],
    });
  });
}

