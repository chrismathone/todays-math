/**
 * **발문이 부른 것은 발문에 있어야 한다** — 학년을 넘는 축이라 여기 따로 둔다.
 *
 * ## 왜 생겼나
 *
 * 2026-08-23 소단원 조건 판정기 dry-run 이 초3 1-2-3 심화에서 이것을 물었다:
 *
 *   「가, 나, 다 는 삼각형이고 라는 사각형입니다. **두 조건**을 모두 채우는 도형의 개수를」
 *
 * 그 두 조건이 **발문에도 그림에도 없다.** 해설에만 있었고(「변이 셋」·「직각이 있다」),
 * 그림은 `pointGrid` 라 글자가 없다. 값은 맞는데 **학생이 풀 수 없는 문항**이다(40씨앗 중 3).
 *
 * ## 왜 소단원 조건 판정기가 이걸 못 잡나 — **다른 축이다**
 *
 * 그쪽은 **발문 + 해설**을 본다. 그래야만 하는 까닭이 있다: 기본(2단) 갈래는 **일부러
 * 이름을 안 쓰고 성질로 말한다**(「종이를 두 번 접어 만든 각과 같은 삼각형」). 「발문에도
 * 있어야」로 조이면 **거짓 경보 1273건**이 돌아오고, 그러면 그 가드가 꺼진다.
 * 이 결함은 해설에는 멀쩡히 있으므로 그쪽 축으로는 구조적으로 안 잡힌다.
 *
 * ## ⚠️ 이 시험의 사각지대 — 열쇠가 **손**이다
 *
 * 이 시험은 발문이 조건을 **「두 조건」이라는 낱말로 부르는 자리만** 본다. 다른 낱말로
 * 부르면 못 본다. 좁게 잡은 것은 일부러다 — 「조건」까지 넓히면 초3 1-6-4·1-6-5·1-6-7
 * 심화의 「**조건에 맞는** $\square$ 는 몇 개인가」가 걸리는데, 그쪽은 조건이 바로 아래
 * **부등식으로** 적혀 있다(말이 아니라 식일 뿐 결함이 아니다). **거짓 경보는 가드를 끈다.**
 *
 * 그리고 **그 손 열쇠가 하루에 두 번 눈멀었다.** 축을 재려고 만든 임시 계량기에서:
 *   ㉠ 「조건을 적었나」에 `이고 ` 를 넣었더니 「삼각형**이고** 라는 사각형입니다」가
 *      걸려 **자기가 겨눈 그 결함을 못 봤다.** 0 이 나왔고 그건 «깨끗»이 아니었다.
 *   ㉡ 반대로 `초과|미만` 이 빠져 초5 2-1-3(「$13$살 **초과**」)이 **40자리 거짓**이었다.
 * **손 목록은 양쪽으로 샌다.** 그래서 아래 분모 가드가 이 파일의 핵심이다 —
 * 「0 = 못 셈」을 구조적으로 불가능하게 만든다.
 *
 * ## 왜 판정기(`probe-elem-*`)로 안 만들었나
 *
 * 이 축의 결함은 트리 전체에서 **그 하나뿐**이었고 고쳤다(전 학년·갈래 전량·씨앗 40 에서
 * 모집단 145자리 중 1갈래). 새 판정기는 태어나자마자 0을 찍는데, 그 0 의 뜻을 정하는 것이
 * 바로 위의 손 열쇠다 — 두 번 눈먼 그것이다. 그래서 **분모를 세는 시험**으로 둔다
 * (2026-08-23 리드 승인). `elemProbeGauges` 의 표에는 넣지 않는다 — 그 표는
 * `probe-elem-*.ts` 판정기용이고 디렉터리 대조가 있어 시험 파일을 넣으면 어긋난다.
 */
import { describe, expect, it } from "vitest";

import { ELEM_TIERS } from "@/lib/elementary/difficulty";
import {
  elementaryUnits,
  generateElementaryProblem,
  supportedTiers,
} from "@/lib/elementary/generate";

const SEEDS = Array.from({ length: 24 }, (_, i) => 20260823 + i * 7919);

describe("[초등] 발문이 부른 조건은 발문에 적혀 있다", () => {
  it("「두 조건」이라 했으면 그 둘을 발문이 이름으로 댄다 (전 학년)", () => {
    const units = elementaryUnits();
    expect(units.length, "초등 소단원을 하나도 못 찾았다").toBeGreaterThan(100);

    let looked = 0;
    for (const u of units) {
      const tiers = supportedTiers(u).length > 0 ? ELEM_TIERS : [];
      for (const tier of [undefined, ...tiers])
        for (const seed of SEEDS) {
          const c = generateElementaryProblem(u, seed, tier).content;
          if (!c.includes("두 조건")) continue;
          looked += 1;
          // 조건을 이름으로 대면 낫표로 묶여 **둘**이 선다: 「변이 셋」·「직각이 있다」.
          const quoted = c.match(/「[^」]+」/g) ?? [];
          expect(
            quoted.length,
            `${u.grade} ${u.section} «${tier ?? "표준"}» 씨앗 ${seed} — 「두 조건」이라 부르고 그 조건을 안 적었다: ${c.replace(/\n/g, " / ")}`,
          ).toBeGreaterThanOrEqual(2);
        }
    }

    // **분모를 세는 것이 이 시험의 알맹이다.** 「두 조건」이라 부르는 자리가 하나도
    // 없으면 위 단정은 한 번도 안 돌고, 그러면 초록은 «깨끗»이 아니라 «못 셈»이다.
    expect(
      looked,
      "「두 조건」이라 부르는 발문이 하나도 없다 — 축이 사라졌다. 문형이 바뀌었으면 열쇠를 옮기고, 아니면 이 시험은 아무것도 재고 있지 않다",
    ).toBeGreaterThan(0);
  });
});
