describe("5차 물결 확대 갈래 — 지면의 말 고정", () => {
  it("표가 등록 유형 전량을 덮는다 — 유형을 더하고 표를 안 늘리면 빨개진다", () => {
    const all = [...new Set(ENTRIES.map((e) => e.key))];
    const inPages = new Set(PAGES.map((p) => p.key));
    const inDigests = new Set(DIGESTS.map(([k]) => k));
    expect(
      all.filter((k) => !inPages.has(k)),
      "전문 표에 없는 유형",
    ).toEqual([]);
    expect(
      all.filter((k) => !inDigests.has(k)),
      "지문 표에 없는 유형",
    ).toEqual([]);
    expect(PAGES).toHaveLength(all.length * 2);
    for (const [key, hs] of DIGESTS) expect(hs, key).toHaveLength(DIGEST_COUNT);
  });

  for (const page of PAGES) {
    it(`${page.key} · 씨앗 ${page.seed} — 지면 전문이 한 글자도 안 바뀐다`, () => {
      const entry = ENTRIES.find((e) => e.key === page.key);
      expect(entry, page.key).toBeDefined();
      const got = entry!.handler(createRng(page.seed));
      expect(got.content).toBe(page.content);
      expect(got.answer).toBe(page.answer);
      expect(got.solution).toBe(page.solution);
    });
  }

  for (const [key, want] of DIGESTS) {
    it(`${key} — 씨앗 ${DIGEST_COUNT}개의 지면 지문이 그대로다`, () => {
      const entry = ENTRIES.find((e) => e.key === key);
      expect(entry, key).toBeDefined();
      const got = want.map((_, i) => {
        const p = entry!.handler(createRng(digestSeed(i)));
        return createHash("md5")
          .update([p.content, p.answer, p.solution].join("::"))
          .digest("hex")
          .slice(0, 12);
      });
      // 어느 씨앗이 바뀌었는지 판정 문구가 대야 한다.
      const moved = want
        .map((w, i) => (w === got[i] ? null : digestSeed(i)))
        .filter(Boolean);
      expect(moved, `${key} — 지면이 바뀐 씨앗`).toEqual([]);
    });
  }
});
