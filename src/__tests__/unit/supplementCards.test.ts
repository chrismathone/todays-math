// 두 조각이 대등하게 이어지는 가운데 조각 — «A = B» · «A과 B» · «A와 B» · «A 및 B»(본 카드 대칭 시험과 같은 식)
const SYMMETRIC_JOIN = /(=|과|와|및)\s*$/;
// 활용 끝을 떼어 낸 줄기 — 오답 말이 정답 말과 줄기가 같으면 같은 뜻을 다른 칸 꼴로 넣을 수 있다(본 카드 대칭 시험과 같은 목록).
const ENDINGS = [
  "진다",
  "지고",
  "지며",
  "지는",
  "진",
  "한다",
  "하고",
  "하며",
  "하다",
  "하는",
  "한",
  "이다",
  "이고",
  "이며",
  "인",
  "된다",
  "되고",
  "되며",
  "되는",
  "된",
  "는다",
  "다",
  "고",
  "며",
  "는",
];
const stem = (word: string) => {
  const t = word.replace(/\s+/g, "");
  const ending = ENDINGS.find((e) => t.length > e.length && t.endsWith(e));
  return ending ? t.slice(0, -ending.length) : t;
};

describe("보충 카드 21장 — 12가지 채움 · 대등 잇기 · 활용형", () => {
  it("감사 표 = 21장 × 12가지 채움 — 만든 문장이 표와 같고, 정답 채움만 «정답»이며 나머지 11가지는 거짓 또는 말이 안 됨", () => {
    expect(Object.keys(FILL_AUDIT)).toEqual(IDS);
    for (const card of supplementCards) {
      const made: string[] = [];
      for (let i = 0; i < 4; i++)
        for (let j = 0; j < 4; j++)
          if (i !== j)
            made.push(
              card.pieces[0]! +
                card.words[i] +
                card.pieces[1] +
                card.words[j] +
                card.pieces[2],
            );
      const rows = FILL_AUDIT[card.id]!;
      expect({ id: card.id, made }).toEqual({
        id: card.id,
        made: rows.map(([sentence]) => sentence),
      });
      // 정답 채움(말 0 · 1)은 첫 줄 하나뿐이고, 그 문장이 뜻 문장이다.
      expect(rows.filter(([, verdict]) => verdict === "정답")).toEqual([
        [card.definition, "정답"],
      ]);
      for (const [sentence, verdict] of rows.slice(1))
        expect({
          id: card.id,
          sentence,
          ok: /^(거짓 — .+|말이 안 됨)$/.test(verdict),
        }).toEqual({
          id: card.id,
          sentence,
          ok: true,
        });
    }
  });

  it("가운데 조각이 대등하게 잇는 꼴(«=» · «…과» · «…와» · «및»)이 아니다", () => {
    for (const card of supplementCards)
      expect({
        id: card.id,
        join: SYMMETRIC_JOIN.test(card.pieces[1]!),
      }).toEqual({ id: card.id, join: false });
    expect(SYMMETRIC_JOIN.test(" 곱한 값과 ")).toBe(true);
  });

  it("오답 말이 정답 말의 활용형이 아니다", () => {
    for (const card of supplementCards) {
      const [a0, a1, ...wrong] = card.words;
      for (const d of wrong)
        expect({
          id: card.id,
          d,
          same: [a0!, a1!].filter((a) => stem(a) === stem(d!)),
        }).toEqual({ id: card.id, d, same: [] });
    }
    expect(stem("같고")).toBe(stem("같다"));
  });
});

