describe("검토 원장", () => {
  it("초등 잔고가 실측 그대로다 (2026-08-25) — 조용히 늘지 못한다", () => {
    // 122행(4단 87 · 고칠것 35)에서 시작했다. 초6 1-4 다섯 갈래를 고쳐
    //   · 1-4-1 은 발문이 「전체가 … 일 때」를 쓰게 되어 **표지가 붙었다** → 행을 지웠다(122→121)
    //   · 1-4-2~1-4-5 는 표지 없이 두 걸음이 되었다 → 고칠것 → 4단 (35→30 · 87→91)
    // 이어서 초6 나머지 넷(1-2-1 · 2-3-2 · 2-3-4 · 2-4-2)을 고쳤다 —
    //   2-3-2 는 「만들었더니 … 남았습니다」로 **표지가 붙어** 행을 지웠고(121→120),
    //   나머지 셋은 표지 없이 두 걸음이 되었다 (30→26 · 91→94).
    // 초5 1-2 셋(1-2-1 · 1-2-3 · 1-2-5)도 고쳤다 — 셋 다 「어떤 수/어떤 두 수」
    //   표지가 붙어 행을 지웠다 (120→117 · 고칠것 26→23).
    // 초4 아홉(1-1-1 · 1-1-3~5 · 1-2-2 · 1-2-5 · 1-2-6 · 1-3-7 · 1-6-2)도 고쳤다 —
    //   아홉 다 표지가 없어 행은 남고 판정만 4단으로 바뀐다 (고칠것 23→14 · 4단 94→103).
    // 마지막으로 초3 열넷 — **잔고가 $0$ 이 되었다**(14→0 · 103→117).
    // ⚠️ 잔고 $0$ 은 «표지 없는 갈래를 사람이 다 봤고 다 고쳤다»는 뜻이지
    //    «심화가 전부 4단이다»가 아니다. 표지가 붙은 갈래는 사람이 안 봤다 —
    //    그 사각지대는 `census-elem-deep-steps.ts` 가 수로 찍는다(70갈래).
    // 고친 갈래의 행을 안 지우면 판정기가 「낡은 행」으로 빨개진다(probe-elem-tier-4dan).
    const rows = Object.values(ledger.초등);
    expect(rows.length).toBe(117);
    expect(rows.filter((r) => r.판정 === "4단").length).toBe(117);
    expect(rows.filter((r) => r.판정 === "고칠것").length).toBe(0);
  });

  it("중등 잔고가 실측 그대로다 (2026-08-25)", () => {
    const rows = Object.values(ledger.중등);
    expect(rows.length).toBe(13);
    expect(rows.filter((r) => r.판정 === "고칠것").length).toBe(0);
  });

  it("행마다 «왜»가 있다 — 없으면 다음 사람이 처음부터 다시 본다", () => {
    for (const [k, r] of Object.entries({ ...ledger.초등, ...ledger.중등 })) {
      expect(r.왜.length, k).toBeGreaterThan(10);
      expect(r.이름.length, k).toBeGreaterThan(0);
      expect(r.본날, k).toMatch(/^\d{4}-\d{2}-\d{2}$/);
    }
  });

  it("초등 키는 «학년|소단원 코드» 다 — 이름이 바뀌어도 안 끊긴다", () => {
    for (const k of Object.keys(ledger.초등))
      expect(k, k).toMatch(/^초[3-6]\|\d+-\d+-\d+$/);
    expect(elemKey("초3", "1-2-5 정사각형 알아보기")).toBe("초3|1-2-5");
  });
});

describe("중등 열쇠는 D-106 의 것과 한 벌이다", () => {
  it("`tier.ts` 의 계산 지시 낱말과 같은 집합이다", () => {
    const src = readFileSync("src/lib/middle/tier.ts", "utf-8");
    const line = src.match(/const OPERATION_INSTRUCTION\s*=\s*\/\(([^)]*)\)/);
    expect(
      line,
      "tier.ts 의 OPERATION_INSTRUCTION 을 못 찾았다",
    ).not.toBeNull();
    const 낱말 = line![1]!.split("|").map((w) => w.trim());
    expect([...낱말].sort()).toEqual([...OPERATION_INSTRUCTION_WORDS].sort());
  });
});
