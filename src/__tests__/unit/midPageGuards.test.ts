/**
 * 공용 지면 가드(`../helpers/midPage.ts`)의 **눈금** — 2026-09-27 리드 결정으로 중등 시험 둘이
 * 따로 들고 있던 자를 공용 가드로 올리면서, 그 자의 양성·음성 눈금도 여기로 옮겼다.
 *
 *  ⑴ `blindJosa` — `josaMismatches` 의 사각(수 뒤 주격 「이」, 문자·제곱·프라임 뒤, 「로/으로」,
 *     「(이)라」). 둘을 함께 부르는 `josaFaults` 가 전 유형 시험의 판정이다 — 아래 「배선」 눈금이
 *     그 사실을 지킨다(배선을 따로 두었을 때 자를 떼어 내도 아무도 안 울었다 — 변이 J10).
 *     `josaMismatches` 에 섞지 않은 까닭은 `midPage.josaFaults` 머리말(고등 `highIdentity`).
 *  ⑵ `pageSmells` 「맨 괄호 앞에 계수 1 을 적었다」 — `$1(a+b)$`. 수식 안에서만, `{` 바로 뒤는 뺀다.
 *
 * 올리지 **않은** 것: 「상수 0」을 식에 붙은 것만으로 좁히기. `middleM3Top2`(41U·42U 가 실제로
 * 낸 `$-8+0=-8$`)·`middleM1Top5g`(`$3-0=3$`)가 넓은 규칙에 기대 잠그고 있어, 좁히면 그 잠금이
 * 소리 없이 약해진다. 좁은 자는 `middleNotationAll` 에 그대로 있다.
 */
import { describe, expect, it } from "vitest";

import {
  blindJosa,
  josaFaults,
  josaMismatches,
  pageSmells,
} from "../helpers/midPage";

describe("blindJosa 눈금 — 양성은 잡고 음성은 안 잡는다", () => {
  it("수 뒤 주격 「이」, 문자·제곱·프라임 뒤 조사, 「로/으로」, 「(이)라」 를 잡는다", () => {
    for (const [t, want] of [
      ["최소공배수가 $252$이 되어야 한다.", "$…252$이 → 가"],
      ["$-5+20=15$이 되어", "$…-5+20=15$이 → 가"],
      ["평면 $P$ 위에 점 $A$, $B$이 있고", "$…B$이 → 가"],
      ["두 수를 빼면 $R$가 지워지므로", "$…R$가 → 이"],
      ["$\\overline{FD}$은 $\\overline{AB}$에", "$…\\overline{FD}$은 → 는"],
      ["$A\\times2x^{2}$를 계산하시오.", "$…A\\times2x^{2}$를 → 을"],
      ["점 $(-3, t)$을 지날 때", "$…(-3, t)$을 → 를"],
      ["분모를 $3$로 통분하여", "$…3$로 → 으로"],
      ["분모를 $10$로 통분하여", "$…10$로 → 으로"],
      ["$(x-y)^2$ 로 인수분해한 뒤", "$…(x-y)^2$로 → 으로"],
      ["$y=ax(x-3)$로 놓는다", "$…y=ax(x-3)$로 → 으로"],
      ["$n$로 나누면", "$…n$로 → 으로"],
      ["$r$는 반지름", "$…r$는 → 은"],
      ["나머지를 $R$라 하면", "$…R$라 → 이라"],
      ["구하는 식을 $y=mx+8$라 하자.", "$…y=mx+8$라 → 이라"],
      ["두 수를 $x$, $x+14$이라 하고", "$…x+14$이라 → 라"],
      ["$-2\\le x$을 만족시키는", "$…-2\\le x$을 → 를"],
      // 프라임 — 「프라임」(받침 ㅁ)으로 읽는다(원장님 2026-09-27)
      ["삼각형 $AEB'$와 삼각형 $DB'C$", "$…AEB'$와 → 과"],
      ["접선을 $TT'$라 하고", "$…TT'$라 → 이라"],
      ["$\\overline{BA'}$가 지름이므로", "$…\\overline{BA'}$가 → 이"],
      ["$A'$로 옮긴 점", "$…A'$로 → 으로"],
    ] as const) {
      expect(blindJosa(t), t).toEqual([want]);
    }
  });

  it("서술격·단위·지시어·옳은 조사(프라임 포함)는 조용하다", () => {
    for (const t of [
      "합은 $75$이다.",
      "$5$이고 $x$이므로",
      "소금물 $184\\,\\mathrm{g}$이 있다.", // 그램이
      "높이가 $108\\,\\mathrm{m}$가 되는", // 미터가
      "길이가 $20 cm$가 되는", // 센티미터가
      "넓이가 $16\\,\\mathrm{cm^2}$가 되는",
      "물 $5\\,\\mathrm{L}$를 부었더니", // 리터를
      "지름 $BA'$을 그으면", // 프라임을
      "무게중심을 $G'$이라 하면",
      "$\\overline{BA'}$이 지름이므로",
      "삼각형 $AEB'$과 삼각형",
      "$10$, $11$, $15$\n이 자료의", // 줄이 바뀐 뒤의 「이」는 지시어
      "$252$가 되어야",
      "점 $A$, $B$가 있고",
      "$R$이 지워지므로",
      "$2x^{2}$을 곱했더니",
      "$y=x$가 성립한다",
      "분모를 $3$으로 통분하여",
      "$5$로 나누면",
      "$1$로",
      "$7$로",
      "$l$로",
      "$x$로 나타내면",
      "$3$가지",
      "$4$과목",
      "세로의 길이를 $x cm$라 하면", // 센티미터라
      "남은 길이를 $y cm$라 하면",
      "나머지를 $R$이라 하면",
      "구하는 식을 $y=mx+5$라 하자.",
      "$\\dfrac{1}{2}$로", // 분수 — 읽는 순서가 달라 판정 안 함
    ]) {
      expect(blindJosa(t), t).toEqual([]);
    }
  });

  it("배선 — `josaFaults` 가 수 뒤 조사와 사각을 함께 본다", () => {
    expect(josaFaults("$x=20$를 대입하면")).toEqual(["$…x=20$를 → 을"]);
    expect(josaFaults("분모를 $3$로 통분하여")).toEqual(["$…3$로 → 으로"]);
    expect(josaFaults("평면 $P$ 위에 점 $A$, $B$이 있고")).toEqual([
      "$…B$이 → 가",
    ]);
    expect(josaFaults("$x=20$을 대입하면 $3$으로 나눈다")).toEqual([]);
    // `josaMismatches` 는 수 뒤 조사만 본다(고등이 이것을 쓴다 — 섞지 않은 까닭은 머리말)
    expect(josaMismatches("분모를 $3$로 통분하여")).toEqual([]);
  });
});

describe("pageSmells 「맨 괄호 앞에 계수 1」 눈금", () => {
  const LABEL = "맨 괄호 앞에 계수 1 을 적었다";
  it("수식 안의 맨 괄호 앞 계수 1 을 잡는다", () => {
    for (const t of [
      "$1(a+b)=-8$",
      "$\\{5x-1(20-x)\\}$점",
      "$3(x-6)>1(x+1)$",
      "$-1(x+3)$",
    ]) {
      expect(pageSmells(t), t).toContain(LABEL);
    }
  });

  it("유리화 분자·두 자리 수·소수·함숫값·수식 밖은 잡지 않는다", () => {
    for (const t of [
      "$\\dfrac{1(3-\\sqrt{3})}{6}$",
      "$21(x+1)$",
      "$0.1(x+2)$",
      "$f(1)=3$",
      "문제 1(가)에서 $x=2$",
      "$(x-1)(x+2)=0$",
    ]) {
      expect(pageSmells(t), t).not.toContain(LABEL);
    }
  });
});
